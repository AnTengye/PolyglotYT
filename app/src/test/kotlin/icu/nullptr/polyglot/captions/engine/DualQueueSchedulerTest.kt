    private fun buildMultiBlockTimeline(blockCount: Int): List<CaptionCue> =
        (0 until blockCount).map { i ->
            val start = i * 8_000L
            CaptionCue(
                videoId = "v1",
                startMs = start,
                endMs = start + 7_000L,
                text = "Block sentence number $i.",
            )
        }

    private class FakeHttpURLConnection(
        private val onDisconnectLatch: CountDownLatch? = null,
        private val blockInsideDisconnect: CountDownLatch? = null,
    ) : HttpURLConnection(URL("https://example.com/v1/chat/completions")) {
        val disconnected = AtomicBoolean(false)

        override fun disconnect() {
            disconnected.set(true)
            onDisconnectLatch?.countDown()
            blockInsideDisconnect?.await(2, TimeUnit.SECONDS)
        }

        override fun usingProxy(): Boolean = false
        override fun connect() {}
    }

    @Test
    fun `cold start only bootstraps focusIndex+1 within 20s and unlocks 30s prefetch after everReady`() {
        val now = AtomicLong(0L)
        val startedBlocks = CopyOnWriteArrayList<String>()
        val block0FinishGate = CountDownLatch(1)
        val block1Started = CountDownLatch(1)
        val steadyPrefetchDone = CountDownLatch(4)

        val scheduler = DualQueueScheduler(
            translator = { block, cues, _, control ->
                startedBlocks += block.id
                control.onRequestBodySent()
                if (block.blockIndex == 0) {
                    assertTrue(block0FinishGate.await(2, TimeUnit.SECONDS))
                } else if (block.blockIndex == 1) {
                    block1Started.countDown()
                }
                val result = BlockTranslationOutcome.fromList(cues.map { "ZH:${it.normalizedText}" })
                steadyPrefetchDone.countDown()
                result
            },
            listener = object : TranslationPublishListener {
                override fun onBlockPublished(
                    sessionEpoch: Long,
                    generation: Int,
                    block: PlannedBlock,
                    plan: BlockTranslationPlan,
                ) {}
            },
            clockMs = { now.get() },
            prefetchRateLimiter = GcraRateLimiter(rpm = 0), // unlimited for queue gate test
            enableTimerWakeup = false,
        )

        scheduler.use {
            // 6 authored blocks at 0s, 8s, 16s, 24s, 32s, 40s (each 1 sentence ending with '.')
            val cues = buildMultiBlockTimeline(6)
            val blocks = scheduler.submitTimeline(cues, isAutoGenerated = false, sourceLanguage = "en")
            assertEquals(6, blocks.size)

            // Once block 0 calls onRequestBodySent(), bootstrap block 1 (start=8s <= 20s) starts,
            // while block 2 (16s) and block 3 (24s) MUST NOT start before everReady!
            assertTrue(block1Started.await(2, TimeUnit.SECONDS))
            Thread.sleep(60)
            assertEquals(setOf(blocks[0].id, blocks[1].id), startedBlocks.toSet())

            // Unblock block 0 -> everReady becomes true -> blocks 2 (16s) & 3 (24s <= 30s) prefetch,
            // while block 4 (32s > 30s) stays outside +30s window!
            block0FinishGate.countDown()
            assertTrue(steadyPrefetchDone.await(2, TimeUnit.SECONDS))
            Thread.sleep(60)
            assertEquals(
                setOf(blocks[0].id, blocks[1].id, blocks[2].id, blocks[3].id),
                startedBlocks.toSet(),
            )
        }
    }

    @Test
    fun `pendingFocus replaces intermediate seek targets without charging retry attempts`() {
        val now = AtomicLong(1_000L)
        val slotGates = ConcurrentHashMap<Int, CountDownLatch>()
        val bothFocusBusy = CountDownLatch(2)
        val executedIndices = CopyOnWriteArrayList<Int>()
        val publishedIndices = CopyOnWriteArrayList<Int>()
        val block4Published = CountDownLatch(1)

        val scheduler = DualQueueScheduler(
            translator = { block, cues, isPriority, control ->
                if (isPriority) {
                    executedIndices += block.blockIndex
                    control.onRequestBodySent()
                    if (block.blockIndex == 0 || block.blockIndex == 1) {
                        bothFocusBusy.countDown()
                        slotGates[block.blockIndex]?.await(2, TimeUnit.SECONDS)
                    }
                }
                BlockTranslationOutcome.fromList(cues.map { "ZH:${block.blockIndex}" })
            },
            listener = object : TranslationPublishListener {
                override fun onBlockPublished(
                    sessionEpoch: Long,
                    generation: Int,
                    block: PlannedBlock,
                    plan: BlockTranslationPlan,
                ) {
                    publishedIndices += block.blockIndex
                    if (block.blockIndex == 4) block4Published.countDown()
                }
            },
            clockMs = { now.get() },
            maxRetriesPerBlock = 0, // 0 retries allowed: proves block 2 & 3 didn't burn attempts!
            prefetchRateLimiter = GcraRateLimiter(rpm = 1), // keep prefetch minimal
            enableTimerWakeup = false,
        )

        scheduler.use {
            slotGates[0] = CountDownLatch(1)
            slotGates[1] = CountDownLatch(1)

            val cues = buildMultiBlockTimeline(6)
            scheduler.submitTimeline(cues, isAutoGenerated = false, sourceLanguage = "en")

            // Seek to block 1 (8s) while block 0 is occupying focus slot #1 -> occupies focus slot #2
            now.addAndGet(200)
            scheduler.onExplicitSeek(8_500L)
            assertTrue(bothFocusBusy.await(2, TimeUnit.SECONDS))

            // Both focus threads are busy! Rapidly scrub across block 2 (16s) -> block 3 (24s) -> block 4 (32s)
            now.addAndGet(100)
            scheduler.onExplicitSeek(16_500L) // pendingFocus = block 2
            now.addAndGet(100)
            scheduler.onExplicitSeek(24_500L) // replaces pendingFocus with block 3
            now.addAndGet(100)
            scheduler.onExplicitSeek(32_500L) // replaces pendingFocus with block 4

            // Release focus slot #1 (block 0 finishes) -> pendingFocus (block 4) promotes immediately!
            slotGates[0]!!.countDown()
            assertTrue(block4Published.await(2, TimeUnit.SECONDS))

            // Blocks 2 and 3 were never dispatched to focusExecutor!
            assertFalse(executedIndices.contains(2))
            assertFalse(executedIndices.contains(3))

            // Now seek back to block 2 (16s): since maxRetriesPerBlock = 0, if block 2 had been
            // charged an attempt while in pendingFocus, it would have FAILED instead of translating!
            val block2Done = CountDownLatch(1)
            slotGates[1]!!.countDown()
            now.addAndGet(200)
            scheduler.onExplicitSeek(16_500L)
            val deadline = System.currentTimeMillis() + 2_000L
            while (System.currentTimeMillis() < deadline) {
                if (publishedIndices.contains(2)) {
                    block2Done.countDown()
                    break
                }
                Thread.sleep(20)
            }
            assertEquals(0L, block2Done.count)
        }
    }

    @Test
    fun `same-video seek cancels unsent attempt immediately while sent attempt caches without stale provisional UI`() {
        val now = AtomicLong(1_000L)
        val unsentConnDisconnected = CountDownLatch(1)
        val sentConn = FakeHttpURLConnection()
        val unsentConn = FakeHttpURLConnection(onDisconnectLatch = unsentConnDisconnected)

        val block0SentReady = CountDownLatch(1)
        val block0ContinueAfterSeek = CountDownLatch(1)
        val block1AttachedUnsent = CountDownLatch(1)
        val block1HoldBeforeSend = CountDownLatch(1)
        val cachedCueTexts = Collections.synchronizedSet(HashSet<String>())
        val provisionalEvents = CopyOnWriteArrayList<String>()
        val block3Done = CountDownLatch(1)
        val block0CachedLatch = CountDownLatch(1)

        val scheduler = DualQueueScheduler(
            translator = { block, cues, _, control ->
                when (block.blockIndex) {
                    0 -> {
                        control.onConnection(sentConn)
                        control.onRequestBodySent()
                        control.onProvisional(0, "DRAFT_GEN0_VISIBLE")
                        block0SentReady.countDown()
                        block0ContinueAfterSeek.await(2, TimeUnit.SECONDS)
                        // Emit late provisional AFTER seek advanced generation -> must be suppressed!
                        control.onProvisional(0, "DRAFT_STALE_AFTER_SEEK")
                        BlockTranslationOutcome.fromList(cues.map { "FINAL_BLOCK_0" })
                    }
                    1 -> {
                        control.onConnection(unsentConn)
                        block1AttachedUnsent.countDown()
                        block1HoldBeforeSend.await(2, TimeUnit.SECONDS)
                        if (control.isCancelled()) throw InterruptedException("cancelled before send")
                        BlockTranslationOutcome.fromList(cues.map { "FINAL_BLOCK_1" })
                    }
                    else -> {
                        control.onRequestBodySent()
                        BlockTranslationOutcome.fromList(cues.map { "FINAL_BLOCK_${block.blockIndex}" })
                    }
                }
            },
            listener = object : TranslationPublishListener {
                override fun onProvisional(
                    sessionEpoch: Long,
                    generation: Int,
                    cue: IndexedCue,
                    translated: String,
                ) {
                    provisionalEvents += translated
                }

                override fun onBlockPublished(
                    sessionEpoch: Long,
                    generation: Int,
                    block: PlannedBlock,
                    plan: BlockTranslationPlan,
                ) {
                    if (block.blockIndex == 3) block3Done.countDown()
                }

                override fun onCacheableEntries(
                    sessionEpoch: Long,
                    entries: Map<IndexedCue, String>,
                ) {
                    entries.values.forEach { cachedCueTexts += it }
                    if ("FINAL_BLOCK_0" in entries.values) block0CachedLatch.countDown()
                }
            },
            clockMs = { now.get() },
            maxRetriesPerBlock = 0,
            prefetchRateLimiter = GcraRateLimiter(rpm = 0),
            enableTimerWakeup = false,
        )

        scheduler.use {
            val cues = buildMultiBlockTimeline(5)
            scheduler.submitTimeline(cues, isAutoGenerated = false, sourceLanguage = "en")

            assertTrue(block0SentReady.await(2, TimeUnit.SECONDS))
            assertTrue(block1AttachedUnsent.await(2, TimeUnit.SECONDS))

            // Seek to block 3 (24_500ms):
            // - Block 1 is unsent -> cancelled & disconnected immediately!
            // - Block 0 is already sent -> NOT disconnected, finishes & caches, stale provisional dropped!
            now.addAndGet(300)
            scheduler.onExplicitSeek(24_500L)
            block1HoldBeforeSend.countDown()

            assertTrue(unsentConnDisconnected.await(2, TimeUnit.SECONDS))
            assertFalse("Already-sent socket must NOT be disconnected on same-video seek", sentConn.disconnected.get())

            block0ContinueAfterSeek.countDown()
            assertTrue(block3Done.await(2, TimeUnit.SECONDS))
            assertTrue(block0CachedLatch.await(2, TimeUnit.SECONDS))

            assertEquals(listOf("DRAFT_GEN0_VISIBLE"), provisionalEvents.toList())
            assertTrue(cachedCueTexts.contains("FINAL_BLOCK_0"))
        }
    }

    @Test
    fun `onNewSession increments epoch disconnects asynchronously without blocking caller and drops stale results`() {
        val disconnectEntered = CountDownLatch(1)
        val unblockDisconnect = CountDownLatch(1)
        val slowConn = FakeHttpURLConnection(
            onDisconnectLatch = disconnectEntered,
            blockInsideDisconnect = unblockDisconnect,
        )
        val requestAttached = CountDownLatch(1)
        val finishOldJob = CountDownLatch(1)
        val publishedFromEpoch = CopyOnWriteArrayList<Long>()
        val cachedFromEpoch = CopyOnWriteArrayList<Long>()

        val scheduler = DualQueueScheduler(
            translator = { _, cues, _, control ->
                control.onConnection(slowConn)
                control.onRequestBodySent()
                requestAttached.countDown()
                finishOldJob.await(2, TimeUnit.SECONDS)
                BlockTranslationOutcome.fromList(cues.map { "OLD_VIDEO_RESULT" })
            },
            listener = object : TranslationPublishListener {
                override fun onBlockPublished(
                    sessionEpoch: Long,
                    generation: Int,
                    block: PlannedBlock,
                    plan: BlockTranslationPlan,
                ) {
                    publishedFromEpoch += sessionEpoch
                }

                override fun onCacheableEntries(
                    sessionEpoch: Long,
                    entries: Map<IndexedCue, String>,
                ) {
                    cachedFromEpoch += sessionEpoch
                }
            },
            enableTimerWakeup = false,
        )

        try {
            val epoch1 = scheduler.currentSessionEpoch()
            scheduler.submitTimeline(buildMultiBlockTimeline(2), isAutoGenerated = false)
            assertTrue(requestAttached.await(2, TimeUnit.SECONDS))

            // Switch video while slowConn.disconnect() blocks for up to 2s -> caller must return immediately!
            val startNano = System.nanoTime()
            val epoch2 = scheduler.onNewSession("video_switched")
            val callerElapsedMs = (System.nanoTime() - startNano) / 1_000_000L

            assertTrue("Epoch must advance", epoch2 > epoch1)
            assertTrue("onNewSession must never block on disconnect(), took ${callerElapsedMs}ms", callerElapsedMs < 200L)
            assertTrue(disconnectEntered.await(2, TimeUnit.SECONDS))

            unblockDisconnect.countDown()
            finishOldJob.countDown()
            Thread.sleep(80)

            // STOPPED session must not publish UI or cache entries
            assertTrue(publishedFromEpoch.isEmpty())
            assertTrue(cachedFromEpoch.isEmpty())
        } finally {
            unblockDisconnect.countDown()
            scheduler.close()
        }
    }

    @Test
    fun `partial batch outcome publishes valid lines immediately and runs single bounded gap-fill for missing indices`() {
        val calls = CopyOnWriteArrayList<List<String>>()
        val publishedPlans = CopyOnWriteArrayList<BlockTranslationPlan>()
        val finalReady = CountDownLatch(1)

        val scheduler = DualQueueScheduler(
            translator = { _, cuesToTranslate, _, control ->
                val texts = cuesToTranslate.map { it.normalizedText }
                calls += texts
                control.onRequestBodySent()
                if (calls.size == 1) {
                    // Initial batch of 3 cues drops index 1 (middle cue)
                    BlockTranslationOutcome(
                        indexedTranslations = mapOf(
                            0 to "第一句译文",
                            2 to "第三句译文",
                        ),
                    )
                } else {
                    // Gap-fill batch asks ONLY for the 1 missing cue
                    BlockTranslationOutcome(
                        indexedTranslations = mapOf(0 to "补漏第二句译文"),
                    )
                }
            },
            listener = object : TranslationPublishListener {
                override fun onBlockPublished(
                    sessionEpoch: Long,
                    generation: Int,
                    block: PlannedBlock,
                    plan: BlockTranslationPlan,
                ) {
                    publishedPlans += plan
                    if (!plan.partial) finalReady.countDown()
                }
            },
            enableTimerWakeup = false,
        )

        scheduler.use {
            val cues = listOf(
                CaptionCue("v1", 0, 1_500, "First fragment"),
                CaptionCue("v1", 1_600, 3_000, "Second fragment"),
                CaptionCue("v1", 3_100, 4_500, "Third fragment."),
            )
            scheduler.submitTimeline(cues, isAutoGenerated = false, sourceLanguage = "en")
            assertTrue(finalReady.await(2, TimeUnit.SECONDS))

            assertEquals(2, calls.size)
            assertEquals(listOf("First fragment", "Second fragment", "Third fragment."), calls[0])
            assertEquals(listOf("Second fragment"), calls[1])

            assertEquals(2, publishedPlans.size)
            assertTrue(publishedPlans[0].partial)
            assertEquals(listOf(1), publishedPlans[0].missingLocalIndices)
            assertFalse(publishedPlans[1].partial)
            assertEquals("补漏第二句译文", publishedPlans[1].translationsByCueIndex[1])
        }
    }

    @Test
    fun `cache warmup serves full hits without network calls and fatal 401 halts retries`() {
        val networkCalls = AtomicInteger(0)
        val block0Published = CountDownLatch(1)
        val block1Failed = CountDownLatch(1)

        val scheduler = DualQueueScheduler(
            translator = { _, _, _, control ->
                networkCalls.incrementAndGet()
                control.onRequestBodySent()
                block1Failed.countDown()
                throw BlockTranslationException("HTTP 401 invalid_api_key", FailureKind.FATAL_CONFIG)
            },
            cacheLookup = { block ->
                if (block.blockIndex == 0) {
                    mapOf(0 to "缓存命中的首句")
                } else {
                    null
                }
            },
            listener = object : TranslationPublishListener {
                override fun onBlockPublished(
                    sessionEpoch: Long,
                    generation: Int,
                    block: PlannedBlock,
                    plan: BlockTranslationPlan,
                ) {
                    if (block.blockIndex == 0) block0Published.countDown()
                }
            },
            maxRetriesPerBlock = 3,
            enableTimerWakeup = false,
        )

        scheduler.use {
            scheduler.submitTimeline(buildMultiBlockTimeline(3), isAutoGenerated = false)
            assertTrue(block0Published.await(2, TimeUnit.SECONDS))
            assertTrue(block1Failed.await(2, TimeUnit.SECONDS))
            Thread.sleep(80)

            // Block 0 came from cache (0 network calls); Block 1 hit FATAL_CONFIG 401 -> 1 call total, 0 retries, Block 2 halted!
            assertEquals(1, networkCalls.get())
            val states = scheduler.slotStatesSnapshot().toMap()
            assertEquals(BlockState.READY, states["b0_0_0"])
            assertEquals(BlockState.FAILED, states["b1_1_1"])
            assertEquals(BlockState.WAITING, states["b2_2_2"])
        }
    }

    @Test
    fun `submitImmediateCues collapses rolling overlay fragments and translates on priority lane`() {
        val translatedTexts = CopyOnWriteArrayList<String>()
        val done = CountDownLatch(1)

        val scheduler = DualQueueScheduler(
            translator = { block, cues, isPriority, control ->
                assertTrue("Immediate overlay blocks must use priority lane", isPriority)
                assertTrue(block.isImmediate)
                control.onRequestBodySent()
                BlockTranslationOutcome.fromList(cues.map { "译:${it.normalizedText}" })
            },
            listener = object : TranslationPublishListener {
                override fun onBlockPublished(
                    sessionEpoch: Long,
                    generation: Int,
                    block: PlannedBlock,
                    plan: BlockTranslationPlan,
                ) {
                    translatedTexts.addAll(plan.translationsByText.values)
                    done.countDown()
                }
            },
            enableTimerWakeup = false,
        )

        scheduler.use {
            scheduler.submitImmediateCues(
                listOf(
                    CaptionCue("", 1_000, -1, "hello"),
                    CaptionCue("", 1_200, -1, "hello shorts"),
                    CaptionCue("", 1_400, -1, "hello shorts viewer"),
                ),
            )
            assertTrue(done.await(2, TimeUnit.SECONDS))
            assertEquals(listOf("译:hello shorts viewer"), translatedTexts.toList())
        }
    }

    @Test
    fun `transient failures back off 1200-5000-15000ms and abandon block after maxRetriesPerBlock`() {
        val now = AtomicLong(10_000L)
        val attempts = AtomicInteger(0)

        val scheduler = DualQueueScheduler(
            translator = { _, _, _, control ->
                attempts.incrementAndGet()
                control.onRequestBodySent()
                throw BlockTranslationException("HTTP 502 Bad Gateway", FailureKind.TRANSIENT)
            },
            clockMs = { now.get() },
            maxRetriesPerBlock = 3,
            focusExecutor = DirectTestExecutor(),
            enableTimerWakeup = false,
        )

        scheduler.use {
            scheduler.submitTimeline(buildMultiBlockTimeline(1), isAutoGenerated = false)
            // Attempt #1 fails -> backoff 1200ms
            assertEquals(1, attempts.get())
            assertEquals(BlockState.WAITING, scheduler.slotStatesSnapshot()[0].second)

            now.addAndGet(1_100L)
            scheduler.tick()
            assertEquals(1, attempts.get()) // still cooling down

            now.addAndGet(200L) // +1300ms >= 1200ms -> Attempt #2 fails -> backoff 5000ms
            scheduler.tick()
            assertEquals(2, attempts.get())

            now.addAndGet(4_900L)
            scheduler.tick()
            assertEquals(2, attempts.get())

            now.addAndGet(200L) // +5100ms >= 5000ms -> Attempt #3 fails -> backoff 15000ms
            scheduler.tick()
            assertEquals(3, attempts.get())

            now.addAndGet(15_100L) // Attempt #4 (initial + 3 retries) fails -> marked FAILED!
            scheduler.tick()
            assertEquals(4, attempts.get())
            assertEquals(BlockState.FAILED, scheduler.slotStatesSnapshot()[0].second)

            // Advancing clock further never retries an abandoned FAILED block
            now.addAndGet(60_000L)
            scheduler.tick()
            assertEquals(4, attempts.get())
        }
    }
}

private class DirectTestExecutor : java.util.concurrent.AbstractExecutorService() {
    @Volatile private var shutDown = false
    override fun shutdown() { shutDown = true }
    override fun shutdownNow(): MutableList<Runnable> { shutDown = true; return mutableListOf() }
    override fun isShutdown(): Boolean = shutDown
    override fun isTerminated(): Boolean = shutDown
    override fun awaitTermination(timeout: Long, unit: TimeUnit): Boolean = true
    override fun execute(command: Runnable) = command.run()
}

