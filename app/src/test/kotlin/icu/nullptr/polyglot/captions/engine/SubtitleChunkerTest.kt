package icu.nullptr.polyglot.captions.engine

import icu.nullptr.polyglot.captions.CaptionCue
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

class SubtitleChunkerTest {

    private fun cue(startMs: Long, endMs: Long, text: String): CaptionCue =
        CaptionCue(videoId = "vid1", startMs = startMs, endMs = endMs, text = text)

    @Test
    fun `asr first block takes off at 6s while subsequent blocks target 14s`() {
        val cues = listOf(
            cue(0, 2_200, "Welcome back to our deep dive"),
            cue(2_200, 4_500, "into mobile systems engineering"),
            cue(4_500, 6_400, "today we explore caption pipelines."),
            cue(6_500, 11_000, "When you watch a long technical lecture"),
            cue(11_000, 15_500, "latency matters for the very first line"),
            cue(15_500, 21_000, "while steady throughput matters afterward."),
            cue(21_100, 25_000, "That is why dual targets work well."),
        )

        val blocks = SubtitleChunker.planTimeline(
            cues = cues,
            isAutoGenerated = true,
            sourceLanguage = "en",
        )

        assertEquals(3, blocks.size)
        assertEquals(0L, blocks[0].startMs)
        assertEquals(6_400L, blocks[0].endMs)
        assertEquals(3, blocks[0].cues.size)

        assertEquals(6_500L, blocks[1].startMs)
        assertEquals(21_000L, blocks[1].endMs)
        assertEquals(3, blocks[1].cues.size)

        assertEquals(21_100L, blocks[2].startMs)
        assertEquals(25_000L, blocks[2].endMs)
    }

    @Test
    fun `asr first block cuts at 6s on strong syntactic pivot without punctuation`() {
        val cues = listOf(
            cue(0, 3_200, "we built the initial prototype last summer"),
            cue(3_200, 6_300, "to test realtime rendering on phones"),
            cue(6_300, 9_500, "however the network queue kept stalling"),
            cue(9_500, 13_000, "whenever someone scrubbed the timeline"),
        )

        val blocks = SubtitleChunker.planTimeline(
            cues = cues,
            isAutoGenerated = true,
            sourceLanguage = "en",
        )

        assertTrue(blocks.size >= 2)
        assertEquals(6_300L, blocks[0].endMs)
        assertEquals("however the network queue kept stalling", blocks[1].cues.first().normalizedText)
        assertTrue(blocks[0].continuedAfter)
        assertTrue(blocks[1].continuedBefore)
    }

    @Test
    fun `abbreviations do not trigger false sentence boundaries`() {
        val cues = listOf(
            cue(0, 3_500, "We spoke with Dr."),
            cue(3_500, 7_200, "Smith and Prof."),
            cue(7_200, 10_500, "Lee about the experiment."),
            cue(10_600, 14_000, "Everything worked as expected."),
        )

        assertFalse(SubtitleChunker.isTerminal("We spoke with Dr."))
        assertFalse(SubtitleChunker.isTerminal("Smith and Prof."))
        assertFalse(SubtitleChunker.isTerminal("Apples vs."))
        assertTrue(SubtitleChunker.isTerminal("Lee about the experiment."))

        val authored = SubtitleChunker.planTimeline(
            cues = cues,
            isAutoGenerated = false,
            sourceLanguage = "en",
        )
        assertEquals(2, authored.size)
        assertEquals(3, authored[0].cues.size)
        assertEquals(1, authored[1].cues.size)
    }

    @Test
    fun `backward search avoids dependent endings and comparative protected cuts`() {
        val cues = listOf(
            cue(0, 6_000, "this system processes live audio streams continuously"),
            cue(6_000, 12_000, "and adapts batch sizes dynamically under load"),
            cue(12_000, 18_000, "it is much more predictable under jittery cellular networks"),
            cue(18_000, 24_000, "however latency spikes still happen when packets drop"),
            cue(24_000, 29_500, "which makes recovery far more important than"),
            cue(29_500, 34_000, "raw throughput alone in production"),
        )

        val blocks = SubtitleChunker.planTimeline(
            cues = cues,
            isAutoGenerated = true,
            sourceLanguage = "en",
        )

        // Should cut before "however..." or at a safe cue seam, never stranding trailing "than"
        val firstLastText = blocks[0].cues.last().normalizedText
        assertFalse("Should not end block on comparative 'than'", firstLastText.endsWith("than"))
    }

    @Test
    fun `cjk dependent endings are protected during backward cut selection`() {
        val cues = listOf(
            cue(0, 7_000, "今天我们来详细拆解一下移动端实时字幕系统的核心架构"),
            cue(7_000, 14_000, "在多线程高并发场景下队列隔离是非常关键的设计"),
            cue(14_000, 22_000, "同时缓存淘汰机制也需要兼顾内存占用与命中率"),
            cue(22_000, 29_500, "尤其是当用户频繁拖动进度条的时候因为"),
            cue(29_500, 35_000, "后台预取如果不暂停就会浪费大量配额"),
        )

        val blocks = SubtitleChunker.planTimeline(
            cues = cues,
            isAutoGenerated = true,
            sourceLanguage = "zh",
        )

        assertFalse(
            "Block should not cut right after CJK dependent word '因为'",
            blocks[0].cues.last().normalizedText.endsWith("因为"),
        )
    }

    @Test
    fun `authored tracks respect 4 cue limit hard gap and speaker marker`() {
        val cues = listOf(
            cue(0, 2_000, "First fragment of a thought"),
            cue(2_100, 4_000, "second fragment continuing"),
            cue(4_100, 6_000, "third fragment still going"),
            cue(6_100, 8_000, "fourth fragment almost there"),
            cue(8_100, 10_000, "fifth fragment overflows cue cap."),
            cue(10_100, 12_000, ">> Speaker two starts immediately"),
            cue(13_000, 15_000, "After a 1000ms silence gap"),
        )

        val blocks = SubtitleChunker.planTimeline(
            cues = cues,
            isAutoGenerated = false,
            sourceLanguage = "en",
        )

        assertEquals(4, blocks.size)
        assertEquals(4, blocks[0].cues.size)
        assertTrue(blocks[0].isAuthored)
        // Cue 4 ("fifth fragment...") ends with '.', so it closes block[1] before ">> Speaker two"
        assertEquals(1, blocks[1].cues.size)
        // Cue 5 ("Speaker two...") is followed by a 1000ms (>= 650ms) hard gap before Cue 6
        assertEquals(1, blocks[2].cues.size)
        assertEquals(1, blocks[3].cues.size)
    }

    @Test
    fun `contextBefore trims farthest prefix and contextAfter trims farthest suffix within 360 chars`() {
        val longEarlyWords = (1..80).joinToString(" ") { "earlyword$it" }
        val nearBeforeMarker = "NEAR_BEFORE_ANCHOR"
        val targetText = "Target cue to translate."
        val nearAfterMarker = "NEAR_AFTER_ANCHOR"
        val longLateWords = (1..80).joinToString(" ") { "lateword$it" }

        val cues = listOf(
            cue(0, 5_000, "$longEarlyWords $nearBeforeMarker."),
            cue(6_000, 9_000, targetText),
            cue(10_000, 16_000, "$nearAfterMarker $longLateWords."),
        )

        val blocks = SubtitleChunker.planTimeline(
            cues = cues,
            isAutoGenerated = false,
            sourceLanguage = "en",
        )

        assertEquals(3, blocks.size)
        val middle = blocks[1]
        assertTrue(middle.contextBefore.length <= SubtitleChunker.MAX_CONTEXT_CHARS)
        assertTrue(middle.contextAfter.length <= SubtitleChunker.MAX_CONTEXT_CHARS)
        assertTrue(
            "contextBefore must preserve tokens closest to block start, got: ${middle.contextBefore}",
            middle.contextBefore.contains(nearBeforeMarker),
        )
        assertFalse(
            "contextBefore should drop far prefix tokens",
            middle.contextBefore.contains("earlyword1 "),
        )
        assertTrue(
            "contextAfter must preserve tokens closest to block end, got: ${middle.contextAfter}",
            middle.contextAfter.startsWith(nearAfterMarker),
        )
        assertFalse(
            "contextAfter should drop far suffix tokens",
            middle.contextAfter.contains("lateword80"),
        )
    }

    @Test
    fun `maxCuesPerBlock=1 supports single-item providers while retaining context`() {
        val cues = listOf(
            cue(0, 2_000, "Line zero context"),
            cue(2_000, 4_000, "Line one target"),
            cue(4_000, 6_000, "Line two after"),
        )

        val blocks = SubtitleChunker.planTimeline(
            cues = cues,
            isAutoGenerated = true,
            sourceLanguage = "en",
            maxCuesPerBlock = 1,
        )

        assertEquals(3, blocks.size)
        assertTrue(blocks.all { it.cues.size == 1 })
        assertTrue(blocks[1].contextBefore.contains("Line zero context"))
        assertTrue(blocks[1].contextAfter.contains("Line two after"))
    }

    @Test
    fun `collapseRollingCues folds progressive ASR prefixes and duplicates`() {
        val rolling = listOf(
            cue(1_000, -1, "we are"),
            cue(1_300, -1, "we are building"),
            cue(1_700, 3_200, "we are building a fast"),
            cue(1_700, 3_500, "we are building a fast"),
            cue(3_600, 3_900, "a fast"),
            cue(7_000, 9_000, "completely separate next sentence"),
        )

        val collapsed = SubtitleChunker.collapseRollingCues(rolling)
        assertEquals(2, collapsed.size)
        assertEquals("we are building a fast", collapsed[0].text)
        assertEquals(1_000L, collapsed[0].startMs)
        assertEquals(3_900L, collapsed[0].endMs)
        assertEquals("completely separate next sentence", collapsed[1].text)
    }

    @Test
    fun `inferAutoGenerated distinguishes overlapping unpunctuated ASR from authored cues`() {
        val asrCues = listOf(
            cue(0, 3_000, "so today we are going to"),
            cue(2_500, 5_500, "look at how compilers optimize"),
            cue(5_000, 8_000, "loops when vectorization is enabled"),
        )
        val authoredCues = listOf(
            cue(0, 2_500, "Welcome to the channel."),
            cue(3_000, 6_000, "Let's begin the demonstration!"),
            cue(6_500, 9_000, "Watch the screen carefully."),
        )

        assertTrue(SubtitleChunker.inferAutoGenerated(asrCues))
        assertFalse(SubtitleChunker.inferAutoGenerated(authoredCues))
    }
}
