class CaptionPipelineIntegrationTest {

    private lateinit var server: HttpServer
    private lateinit var diskStore: BoundedMemoryDiskStore
    private var serverPort: Int = 0

    @Volatile
    private var activeConfig: TranslationManager.RuntimeConfig = TranslationManager.RuntimeConfig()

    @Volatile
    private var activeSourceLang: String = "en"

    @Volatile
    private var activeAutoGenerated: Boolean? = true

    @Before
    fun setUp() {
        CaptionLanguageState.reset()
        EndpointCapabilities.clear()
        diskStore = BoundedMemoryDiskStore()
        TranslationManager.diskStoreOverride = diskStore
        TranslationManager.clearCache()

        server = HttpServer.create(InetSocketAddress("127.0.0.1", 0), 0)
        server.executor = Executors.newCachedThreadPool { r ->
            Thread(r, "IntegrationHttpServer").apply { isDaemon = true }
        }
        server.start()
        serverPort = server.address.port

        activeConfig = TranslationManager.RuntimeConfig(
            enabled = true,
            provider = ConfigManager.PROVIDER_OPENAI,
            targetLanguage = "zh-Hans",
            requestTimeoutMs = 10_000,
            maxRetries = 1,
            persistentCacheEnabled = true,
            openAiEndpoint = "http://127.0.0.1:$serverPort/v1",
            openAiApiKey = "sk-test-integration",
            openAiModel = "gpt-4o-mini",
            openAiStreaming = true,
        )
        TranslationManager.runtimeConfigProvider = { activeConfig }
    }

    @After
    fun tearDown() {
        runCatching { server.stop(0) }
        TranslationManager.clearCache()
        TranslationManager.diskStoreOverride = null
        CaptionLanguageState.reset()
    }

    @Test
    fun firstBlock6sPriority_sseProvisionalEarlyPublish_finalPersistence_andZeroNetworkReplay() {
        val httpCalls = AtomicInteger(0)
        val firstChunkObservedProvisional = CountDownLatch(1)
        val allowSecondChunkLatch = CountDownLatch(1)
        val uiNotifications = CopyOnWriteArrayList<Pair<Set<String>, String>>()

        server.createContext("/v1/chat/completions") { exchange ->
            val callIdx = httpCalls.incrementAndGet()
            val reqJson = exchange.requestBody.bufferedReader(Charsets.UTF_8).use { it.readText() }
            val inputTexts = extractInputSubtitleItems(reqJson)

            exchange.responseHeaders.add("Content-Type", "text/event-stream; charset=utf-8")
            exchange.sendResponseHeaders(200, 0)
            exchange.responseBody.bufferedWriter(Charsets.UTF_8).use { writer ->
                // Stream item 0 immediately, then pause on call #1 so test can observe provisional state!
                writer.write(sseDelta("["))
                for (i in inputTexts.indices) {
                    val prefix = if (i == 0) "" else ","
                    val itemJson = "$prefix{\"i\":$i,\"t\":\"译:${inputTexts[i]}\"}"
                    writer.write(sseDelta(itemJson))
                    writer.flush()
                    if (callIdx == 1 && i == 0 && inputTexts.size > 1) {
                        firstChunkObservedProvisional.countDown()
                        allowSecondChunkLatch.await(3, TimeUnit.SECONDS)
                    }
                }
                writer.write(sseDelta("]"))
                writer.write("data: [DONE]\n\n")
                writer.flush()
            }
        }

        val session = CaptionSession(
            configSignatureProvider = {
                "${activeConfig.provider}|${activeConfig.targetLanguage}|${activeConfig.openAiEndpoint}|${activeConfig.openAiModel}"
            },
        )
        val coordinator = CaptionPipelineCoordinator(
            session = session,
            runtimeConfigProvider = { activeConfig },
            sourceLanguageProvider = { activeSourceLang },
            autoGeneratedProvider = { activeAutoGenerated },
            onRefreshUi = { originals, _, source ->
                uiNotifications += originals to source
            },
        )

        try {
            // Build a 22s ASR timeline so SubtitleChunker cuts block 0 around ~6s and block 1 around ~14s+.
            val timeline = listOf(
                CaptionCue(startMs = 0L, endMs = 2_200L, text = "Welcome back to our deep dive"),
                CaptionCue(startMs = 2_200L, endMs = 4_500L, text = "today we explore the kernel"),
                CaptionCue(startMs = 4_500L, endMs = 6_800L, text = "and see how scheduling works."),
                CaptionCue(startMs = 7_500L, endMs = 11_000L, text = "First let us check the run queue"),
                CaptionCue(startMs = 11_000L, endMs = 15_000L, text = "and measure context switch latency."),
                CaptionCue(startMs = 15_800L, endMs = 21_500L, text = "Finally we benchmark real workloads."),
            )

            val blocks = coordinator.onTimelineBuilt(timeline)
            assertTrue("Expected >= 2 semantic blocks (6s bootstrap + ahead)", blocks.size >= 2)
            assertTrue("First ASR block should stay compact (~6s)", blocks[0].endMs - blocks[0].startMs <= 8_000L)

            // 1) Verify SSE provisional arrives BEFORE the rest of block 0 finishes streaming!
            assertTrue(firstChunkObservedProvisional.await(3, TimeUnit.SECONDS))
            awaitCondition(1_500L) {
                session.translationFor("Welcome back to our deep dive") == "译:Welcome back to our deep dive"
            }
            assertTrue(session.isProvisionalTranslation("Welcome back to our deep dive"))
            assertNull("Provisional must NOT persist to L2 disk store", diskStore.getBatch(
                listOf(TranslationManager.buildCacheKey("Welcome back to our deep dive", "en", activeConfig)),
            ).values.firstOrNull())

            // Release remainder of SSE stream and wait for block 0 final commit + L2 disk persistence.
            allowSecondChunkLatch.countDown()
            awaitCondition(3_000L) {
                !session.isProvisionalTranslation("Welcome back to our deep dive") &&
                    session.translationFor("and see how scheduling works.") == "译:and see how scheduling works."
            }
            TranslationManager.flushPendingDiskWrites()
            assertTrue("Final translations must persist into L2 store", diskStore.size() >= 3)
            assertTrue(uiNotifications.any { it.second == "provisional" })

            // Wait for ahead prefetch within +30s window to finish all 6 cues.
            awaitCondition(4_000L) {
                timeline.all { cue -> session.translationFor(cue.text) != null }
            }
            TranslationManager.flushPendingDiskWrites()
            val callsAfterFirstPlay = httpCalls.get()
            assertTrue(callsAfterFirstPlay >= 2)

            // 2) Simulate cold replay: wipe L1 memory & create a brand-new session/coordinator,
            //    keeping only L2 diskStore -> must hit L2 cache with ZERO new HTTP requests!
            coordinator.close()
            TranslationManager.sharedCache.putMemoryOnly(emptyMap())
            // Clear L1 only without clearing L2 diskStore:
            val savedEntries = timeline.associate { cue ->
                val k = TranslationManager.buildCacheKey(cue.normalizedText(), "en", activeConfig)
                k to diskStore.getBatch(listOf(k))[k].orEmpty()
            }
            TranslationManager.clearCache()
            diskStore.putBatch(savedEntries)
            assertEquals("L1 must be empty before replay", 0, TranslationManager.sharedCache.memorySize())

            val replaySession = CaptionSession(configSignatureProvider = { "openai|zh-Hans|replay|gpt-4o-mini" })
            val replayCoordinator = CaptionPipelineCoordinator(
                session = replaySession,
                runtimeConfigProvider = { activeConfig },
                sourceLanguageProvider = { activeSourceLang },
                autoGeneratedProvider = { activeAutoGenerated },
            )
            try {
                replayCoordinator.onTimelineBuilt(timeline)
                awaitCondition(3_000L) {
                    timeline.all { cue -> replaySession.translationFor(cue.text) == "译:${cue.normalizedText()}" }
                }
                assertEquals("Replay must make ZERO network requests", callsAfterFirstPlay, httpCalls.get())
            } finally {
                replayCoordinator.close()
            }
        } finally {
            coordinator.close()
        }
    }

    @Test
    fun midPlaybackSeek_preemptsEarlyBlocks_andTranslatesLandingBlockImmediately() {
        val requestedBatches = Collections.synchronizedList(ArrayList<List<String>>())
        val block0Gate = CountDownLatch(1)
        val block1Gate = CountDownLatch(1)
        val bothEarlyStarted = CountDownLatch(2)

        server.createContext("/v1/chat/completions") { exchange ->
            val reqJson = exchange.requestBody.bufferedReader(Charsets.UTF_8).use { it.readText() }
            val items = extractInputSubtitleItems(reqJson)
            requestedBatches.add(items)

            val firstText = items.firstOrNull().orEmpty()
            if (firstText.contains("Cue_0") || firstText.contains("Cue_1")) {
                bothEarlyStarted.countDown()
                if (firstText.contains("Cue_0")) {
                    block0Gate.await(3, TimeUnit.SECONDS)
                } else {
                    block1Gate.await(3, TimeUnit.SECONDS)
                }
            }

            val jsonBody = buildNonStreamResponse(items)
            val bytes = jsonBody.toByteArray(Charsets.UTF_8)
            exchange.responseHeaders.add("Content-Type", "application/json; charset=utf-8")
            exchange.sendResponseHeaders(200, bytes.size.toLong())
            exchange.responseBody.use { it.write(bytes) }
        }

        activeConfig = activeConfig.copy(openAiStreaming = false)
        activeAutoGenerated = false // Authored blocks (<=4 cues / 20s) for clean deterministic block boundaries.
        val clock = AtomicLong(1_000L)
        val session = CaptionSession(configSignatureProvider = { "openai|zh-Hans|seek|m" })
        val coordinator = CaptionPipelineCoordinator(
            session = session,
            runtimeConfigProvider = { activeConfig },
            sourceLanguageProvider = { activeSourceLang },
            autoGeneratedProvider = { activeAutoGenerated },
            clockMs = clock::get,
        )

        try {
            // 12 authored cues separated by 8s gaps -> 12 distinct blocks spanning 0s..96s.
            val cues = (0 until 12).map { i ->
                CaptionCue(
                    startMs = i * 8_000L,
                    endMs = i * 8_000L + 3_000L,
                    text = "Cue_$i authored sentence.",
                )
            }
            coordinator.onTimelineBuilt(cues)

            // Wait until Block 0 (focus slot 1) and Block 1 (bootstrap prefetch) are in flight.
            assertTrue(bothEarlyStarted.await(3, TimeUnit.SECONDS))

            // User Seeks directly to 72s (Cue_9)! Focus slot 2 is immediately available for Cue_9!
            clock.addAndGet(500L)
            coordinator.onOverlayCues(listOf(cues[9]))

            // Cue_9 must translate immediately on the second foreground lane BEFORE Block 0/1 even finish!
            awaitCondition(2_500L) {
                session.translationFor(cues[9].text) == "译:${cues[9].normalizedText()}"
            }
            // Unvisited middle blocks (e.g. Cue_4 at 32s, Cue_5 at 40s) were skipped completely!
            assertNull(session.translationFor(cues[4].text))
            assertNull(session.translationFor(cues[5].text))

            block0Gate.countDown()
            block1Gate.countDown()
        } finally {
            block0Gate.countDown()
            block1Gate.countDown()
            coordinator.close()
        }
    }

    @Test
    fun sameLanguageVideoSwitch_incrementsEpoch_andIsolatesLateStaleVideo1Responses() {
        val video1InServer = CountDownLatch(1)
        val releaseVideo1 = CountDownLatch(1)

        server.createContext("/v1/chat/completions") { exchange ->
            val reqJson = exchange.requestBody.bufferedReader(Charsets.UTF_8).use { it.readText() }
            val items = extractInputSubtitleItems(reqJson)
            val isVideo1 = items.any { it.startsWith("Video1_") }
            if (isVideo1) {
                video1InServer.countDown()
                releaseVideo1.await(3, TimeUnit.SECONDS)
            }
            val bytes = buildNonStreamResponse(items).toByteArray(Charsets.UTF_8)
            exchange.responseHeaders.add("Content-Type", "application/json; charset=utf-8")
            exchange.sendResponseHeaders(200, bytes.size.toLong())
            exchange.responseBody.use { it.write(bytes) }
        }

        activeConfig = activeConfig.copy(openAiStreaming = false)
        activeAutoGenerated = false
        val session = CaptionSession(configSignatureProvider = { "openai|zh-Hans|switch|m" })
        val coordinator = CaptionPipelineCoordinator(
            session = session,
            runtimeConfigProvider = { activeConfig },
            sourceLanguageProvider = { "en" },
            autoGeneratedProvider = { false },
        )

        try {
            val video1 = listOf(
                CaptionCue(startMs = 0L, endMs = 3_000L, text = "Video1_opening English subtitle."),
            )
            coordinator.onTimelineBuilt(video1)
            val epochVideo1 = session.currentEpoch()
            assertTrue(video1InServer.await(3, TimeUnit.SECONDS))

            // Switch to Video 2 (SAME source language "en"!) while Video 1 HTTP response is still pending.
            val video2 = listOf(
                CaptionCue(startMs = 500L, endMs = 3_500L, text = "Video2_completely different English subtitle."),
            )
            coordinator.onTimelineBuilt(video2)
            val epochVideo2 = session.currentEpoch()
            assertTrue("Epoch must advance on same-language video switch", epochVideo2 > epochVideo1)

            // Let Video 1's late HTTP response return (or get disconnected) and wait for Video 2 to finish.
            releaseVideo1.countDown()
            awaitCondition(3_000L) {
                session.translationFor(video2[0].text) == "译:${video2[0].normalizedText()}"
            }

            // Video 1's stale translation must NEVER leak into Video 2's active CaptionSession!
            assertNull(session.translationFor(video1[0].text))
        } finally {
            releaseVideo1.countDown()
            coordinator.close()
        }
    }

    @Test
    fun persistentCacheSwitchAndClearCache_controlDiskPersistenceAndSessionState() {
        server.createContext("/v1/chat/completions") { exchange ->
            val reqJson = exchange.requestBody.bufferedReader(Charsets.UTF_8).use { it.readText() }
            val items = extractInputSubtitleItems(reqJson)
            val bytes = buildNonStreamResponse(items).toByteArray(Charsets.UTF_8)
            exchange.responseHeaders.add("Content-Type", "application/json; charset=utf-8")
            exchange.sendResponseHeaders(200, bytes.size.toLong())
            exchange.responseBody.use { it.write(bytes) }
        }

        // 1) When persistentCacheEnabled == false, L1 works but L2 diskStore remains empty.
        activeConfig = activeConfig.copy(openAiStreaming = false, persistentCacheEnabled = false)
        activeAutoGenerated = false
        val session = CaptionSession(configSignatureProvider = { "openai|zh-Hans|cache-opt|m" })
        val coordinator = CaptionPipelineCoordinator(
            session = session,
            runtimeConfigProvider = { activeConfig },
            sourceLanguageProvider = { "en" },
            autoGeneratedProvider = { false },
        )

        try {
            val cues = listOf(CaptionCue(startMs = 0L, endMs = 2_000L, text = "Memory only cue."))
            coordinator.onTimelineBuilt(cues)
            awaitCondition(2_500L) {
                session.translationFor("Memory only cue.") == "译:Memory only cue."
            }
            TranslationManager.flushPendingDiskWrites()
            assertTrue(TranslationManager.sharedCache.memorySize() >= 1)
            assertEquals("L2 diskStore must not be written when persistentCacheEnabled=false", 0, diskStore.size())

            // 2) Clear cache wipes L1 + L2 + invalidates session translations.
            TranslationManager.clearCache()
            // Temporarily disable module so clear doesn't immediately re-fetch before assertion:
            activeConfig = activeConfig.copy(enabled = false)
            coordinator.onTranslationCacheCleared()
            assertEquals(0, TranslationManager.sharedCache.memorySize())
            assertNull(session.translationFor("Memory only cue."))
        } finally {
            coordinator.close()
        }
    }

    private fun extractInputSubtitleItems(requestBodyJson: String): List<String> {
        val root = JsonParser.parseString(requestBodyJson).asJsonObject
        val messages = root.getAsJsonArray("messages")
        val userContent = messages.last().asJsonObject.get("content").asString
        val jsonArrayStr = userContent
            .substringAfter("- Respond in JSON]\n")
            .substringBefore("\n\n[Context After")
            .trim()
        val arr = JsonParser.parseString(jsonArrayStr).asJsonArray
        return arr.map { elem ->
            val obj = elem.asJsonObject
            (obj.get("s") ?: obj.get("t") ?: obj.get("text")).asString
        }
    }

    private fun sseDelta(deltaText: String): String {
        val escaped = deltaText
            .replace("\\", "\\\\")
            .replace("\"", "\\\"")
            .replace("\n", "\\n")
        return "data: {\"choices\":[{\"delta\":{\"content\":\"$escaped\"}}]}\n\n"
    }

    private fun buildNonStreamResponse(items: List<String>): String {
        val contentArray = items.mapIndexed { idx, text ->
            val escaped = text.replace("\\", "\\\\").replace("\"", "\\\"")
            "{\"i\":$idx,\"t\":\"译:$escaped\"}"
        }.joinToString(",", prefix = "[", postfix = "]")
        val escapedContent = contentArray.replace("\\", "\\\\").replace("\"", "\\\"")
        return "{\"choices\":[{\"message\":{\"role\":\"assistant\",\"content\":\"$escapedContent\"},\"finish_reason\":\"stop\"}]}"
    }

    private fun awaitCondition(timeoutMs: Long, predicate: () -> Boolean) {
        val deadline = System.nanoTime() + TimeUnit.MILLISECONDS.toNanos(timeoutMs)
        while (System.nanoTime() < deadline) {
            if (predicate()) return
            Thread.sleep(15L)
        }
        assertTrue("Condition was not satisfied within ${timeoutMs}ms", predicate())
    }
