package icu.nullptr.polyglot.captions

import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test

class CaptionLanguageStateTest {

    @Suppress("unused")
    private class FullYouTubeTrack(
        val a: String,
        val b: String,
        val c: String,
        val d: String,
    )

    @Suppress("unused")
    private class MinimalTrack(
        val lang: String,
        val vssId: String,
    )

    @Suppress("unused")
    private class KindOnlyTrack(
        val kind: String,
        val lang: String,
        val url: String,
    )

    @Before
    fun setUp() {
        CaptionLanguageState.reset()
    }

    @After
    fun tearDown() {
        CaptionLanguageState.reset()
    }

    @Test
    fun initialState_defaultsToAutoAndNonAsr() {
        assertEquals("auto", CaptionLanguageState.currentSourceLanguage())
        assertNull(CaptionLanguageState.currentVssId())
        assertFalse(CaptionLanguageState.isAutoGenerated())
        assertNull(CaptionLanguageState.currentTrack())
    }

    @Test
    fun detectsAutoGeneratedAndAuthoredTracks() {
        val asrTrack = FullYouTubeTrack(
            a = "en",
            b = "a.en",
            c = "English (auto-generated)",
            d = "https://www.youtube.com/api/timedtext?v=vid_001&kind=asr&lang=en",
        )
        assertTrue(CaptionLanguageState.updateFromCaptionTrack(asrTrack, "test"))
        assertEquals("en", CaptionLanguageState.currentSourceLanguage())
        assertEquals("a.en", CaptionLanguageState.currentVssId())
        assertTrue(CaptionLanguageState.isAutoGenerated())

        // Switching from ASR (a.en) to authored (.en) on the same video must trigger reset.
        val authoredTrack = FullYouTubeTrack(
            a = "en",
            b = ".en",
            c = "English",
            d = "https://www.youtube.com/api/timedtext?v=vid_001&lang=en",
        )
        assertTrue(CaptionLanguageState.updateFromCaptionTrack(authoredTrack, "test"))
        assertEquals("en", CaptionLanguageState.currentSourceLanguage())
        assertEquals(".en", CaptionLanguageState.currentVssId())
        assertFalse(CaptionLanguageState.isAutoGenerated())
    }

    @Test
    fun sameLanguageDifferentVideo_triggersSessionResetInsteadOfReturningFalse() {
        val video1Track = FullYouTubeTrack(
            a = "en",
            b = "a.en",
            c = "English (auto-generated)",
            d = "https://www.youtube.com/api/timedtext?v=video_AAA111&kind=asr&lang=en",
        )
        val video1Clone = FullYouTubeTrack(
            a = "en",
            b = "a.en",
            c = "English (auto-generated)",
            d = "https://www.youtube.com/api/timedtext?v=video_AAA111&kind=asr&lang=en",
        )
        val video2Track = FullYouTubeTrack(
            a = "en",
            b = "a.en",
            c = "English (auto-generated)",
            d = "https://www.youtube.com/api/timedtext?v=video_BBB222&kind=asr&lang=en",
        )

        assertTrue(CaptionLanguageState.updateFromCaptionTrack(video1Track, "v1"))
        // Re-observing the same track (or a cloned object with identical timedtext URL) mid-video must NOT reset.
        assertFalse(CaptionLanguageState.updateFromCaptionTrack(video1Track, "v1-repeat"))
        assertFalse(CaptionLanguageState.updateFromCaptionTrack(video1Clone, "v1-clone"))

        // Switching to another English video MUST return true so session clears stale cues.
        assertTrue(CaptionLanguageState.updateFromCaptionTrack(video2Track, "v2"))
        assertNotNull(CaptionLanguageState.currentTrackSignature())
    }

    @Test
    fun minimalTrackWithoutUrl_detectsNewTrackInstanceAcrossSameLanguageVideos() {
        val trackVideo1 = MinimalTrack(lang = "ja", vssId = "a.ja")
        val trackVideo2 = MinimalTrack(lang = "ja", vssId = "a.ja")

        assertTrue(CaptionLanguageState.updateFromCaptionTrack(trackVideo1, "v1"))
        assertFalse(CaptionLanguageState.updateFromCaptionTrack(trackVideo1, "v1-same-ref"))
        assertTrue(CaptionLanguageState.updateFromCaptionTrack(trackVideo2, "v2-new-ref"))
    }

    @Test
    fun detectsAsrFromKindFieldOrQueryAndNormalizesChineseAndLegacyCodes() {
        val kindAsr = KindOnlyTrack(
            kind = "asr",
            lang = "iw",
            url = "https://www.youtube.com/api/timedtext?v=vid_heb&kind=asr&lang=iw",
        )
        assertTrue(CaptionLanguageState.updateFromCaptionTrack(kindAsr, "hebrew"))
        assertEquals("he", CaptionLanguageState.currentSourceLanguage())
        assertTrue(CaptionLanguageState.isAutoGenerated())

        val zhTw = MinimalTrack(lang = "zh_TW", vssId = ".zh-TW.track1")
        assertTrue(CaptionLanguageState.updateFromCaptionTrack(zhTw, "zhtw"))
        assertEquals("zh-Hant", CaptionLanguageState.currentSourceLanguage())
        assertEquals(".zh-TW.track1", CaptionLanguageState.currentVssId())
        assertFalse(CaptionLanguageState.isAutoGenerated())
    }

    @Test
    fun ignoresPseudoCaptionOptionsWithoutMutatingCurrentLanguage() {
        val valid = MinimalTrack(lang = "fr", vssId = ".fr")
        assertTrue(CaptionLanguageState.updateFromCaptionTrack(valid, "init"))

        val disableOption = MinimalTrack(lang = "DISABLE_CAPTIONS_OPTION", vssId = "-")
        val autoTranslateOption = MinimalTrack(lang = "AUTO_TRANSLATE_CAPTIONS_OPTION", vssId = "t.zh-Hans")
        assertFalse(CaptionLanguageState.updateFromCaptionTrack(disableOption, "disable"))
        assertFalse(CaptionLanguageState.updateFromCaptionTrack(autoTranslateOption, "auto-trans"))
        assertEquals("fr", CaptionLanguageState.currentSourceLanguage())
    }
}
