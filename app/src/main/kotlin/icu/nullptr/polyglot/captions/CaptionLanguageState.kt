package icu.nullptr.polyglot.captions

import icu.nullptr.polyglot.isModuleInitialized
import icu.nullptr.polyglot.util.logD
import java.lang.ref.WeakReference
import java.lang.reflect.Field
import java.lang.reflect.Modifier
import java.util.Locale

object CaptionLanguageState {
    private const val TAG = "CaptionLanguageState"
    private const val AUTO_LANGUAGE = "auto"
    private const val DISABLE_CAPTIONS_OPTION = "DISABLE_CAPTIONS_OPTION"
    private const val AUTO_TRANSLATE_CAPTIONS_OPTION = "AUTO_TRANSLATE_CAPTIONS_OPTION"

    private val languagePattern = Regex("^[A-Za-z]{2,3}([_-][A-Za-z0-9]{2,8}){0,3}$")

    @Volatile
    private var currentSnapshot: TrackSnapshot? = null

    private var lastTrackRef: WeakReference<Any>? = null

    data class TrackSnapshot(
        val languageCode: String,
        val vssId: String?,
        val isAutoGenerated: Boolean,
        val trackSignature: String,
    )

    fun currentSourceLanguage(): String =
        currentSnapshot?.languageCode?.ifBlank { AUTO_LANGUAGE } ?: AUTO_LANGUAGE

    fun currentVssId(): String? =
        currentSnapshot?.vssId

    fun isAutoGenerated(): Boolean =
        currentSnapshot?.isAutoGenerated ?: false

    fun currentTrackSignature(): String? =
        currentSnapshot?.trackSignature

    fun currentTrack(): TrackSnapshot? =
        currentSnapshot

    @Synchronized
    fun reset() {
        currentSnapshot = null
        lastTrackRef = null
    }

    @Synchronized
    fun updateFromCaptionTrack(track: Any?, source: String): Boolean {
        val info = CaptionTrackInfo.from(track) ?: return false
        if (info.isPseudoOption) return false

        val language = info.languageCode ?: return false
        val next = TrackSnapshot(
            languageCode = language,
            vssId = info.vssId,
            isAutoGenerated = info.isAutoGenerated,
            trackSignature = info.trackSignature,
        )

        val previous = currentSnapshot
        val sameTrackInstance = track != null && lastTrackRef?.get() === track
        val changed = previous == null ||
            previous.trackSignature != next.trackSignature ||
            (!info.hasUrlDiscriminator && !sameTrackInstance)

        lastTrackRef = track?.let(::WeakReference)
        if (!changed) return false

        currentSnapshot = next
        if (isModuleInitialized) {
            logD(
                TAG,
                "Updated YouTube caption track: ${previous?.languageCode ?: AUTO_LANGUAGE} -> $language " +
                    "(vssId=${next.vssId ?: "none"}, asr=${next.isAutoGenerated}) from $source",
            )
        }
        return true
    }

    private data class CaptionTrackInfo(
        val languageCode: String?,
        val vssId: String?,
        val isAutoGenerated: Boolean,
        val isPseudoOption: Boolean,
        val trackSignature: String,
        val hasUrlDiscriminator: Boolean,
    ) {
        companion object {
            fun from(track: Any?): CaptionTrackInfo? {
                if (track == null) return null

                val entries = track.instanceStringEntries()
                if (entries.isEmpty()) return null

                val strings = entries.map { it.second }
                val isPseudoOption = strings.any {
                    it == DISABLE_CAPTIONS_OPTION || it == AUTO_TRANSLATE_CAPTIONS_OPTION
                }
                val extractedVssId = strings.firstNotNullOfOrNull { extractVssId(it) }
                val directLanguage = strings.firstNotNullOfOrNull { normalizeLanguageCode(it) }
                val vssLanguage = extractedVssId?.let(::languageFromVssId)
                    ?: strings.firstNotNullOfOrNull { languageFromVssId(it) }

                val isAutoGenerated = detectAutoGenerated(extractedVssId, strings)
                val hasUrlDiscriminator = strings.any { value ->
                    "://" in value ||
                        value.contains("timedtext", ignoreCase = true) ||
                        value.contains("v=", ignoreCase = false)
                }
                val trackSignature = entries.joinToString(separator = "|") { (fieldId, value) ->
                    "$fieldId=$value"
                }

                return CaptionTrackInfo(
                    languageCode = directLanguage ?: vssLanguage,
                    vssId = extractedVssId,
                    isAutoGenerated = isAutoGenerated,
                    isPseudoOption = isPseudoOption,
                    trackSignature = trackSignature,
                    hasUrlDiscriminator = hasUrlDiscriminator,
                )
            }
        }
    }

    private fun detectAutoGenerated(vssId: String?, strings: List<String>): Boolean {
        if (vssId != null) {
            val loweredVss = vssId.lowercase(Locale.ROOT)
            if (loweredVss.startsWith("a.") || ".a." in loweredVss) {
                return true
            }
        }
        return strings.any { value ->
            value.equals("asr", ignoreCase = true) ||
                value.contains("kind=asr", ignoreCase = true)
        }
    }

    private fun Any.instanceStringEntries(): List<Pair<String, String>> {
        val entries = ArrayList<Pair<String, String>>()
        var clazz: Class<*>? = javaClass
        var depth = 0
        while (clazz != null && clazz != Any::class.java) {
            val fields = clazz.declaredFields.sortedBy { it.name }
            for (field in fields) {
                if (Modifier.isStatic(field.modifiers) || field.type != String::class.java) {
                    continue
                }
                val value = field.getStringOrNull(this)?.trim()
                if (!value.isNullOrEmpty()) {
                    entries += "$depth:${field.name}" to value
                }
            }
            clazz = clazz.superclass
            depth++
        }
        return entries
    }

    private fun Field.getStringOrNull(instance: Any): String? =
        runCatching {
            isAccessible = true
            get(instance) as? String
        }.getOrNull()

    private fun normalizeLanguageCode(value: String): String? {
        val trimmed = value.trim()
        if (trimmed == DISABLE_CAPTIONS_OPTION || trimmed == AUTO_TRANSLATE_CAPTIONS_OPTION) {
            return null
        }
        if (trimmed.length > 24 || !languagePattern.matches(trimmed)) {
            return null
        }

        val parts = trimmed.replace('_', '-')
            .split('-')
            .filter { it.isNotBlank() }
        if (parts.isEmpty()) return null

        val primary = when (parts.first().lowercase(Locale.ROOT)) {
            "iw" -> "he"
            "in" -> "id"
            "jw" -> "jv"
            else -> parts.first().lowercase(Locale.ROOT)
        }
        if (primary == "und" || primary == "asr") return null

        if (primary == "zh") {
            return normalizeChinese(parts)
        }

        val normalized = buildList {
            add(primary)
            parts.drop(1).forEach { add(normalizeLanguageSubtag(it)) }
        }
        return normalized.joinToString("-")
    }

    private fun normalizeChinese(parts: List<String>): String {
        val lowered = parts.joinToString("-").lowercase(Locale.ROOT)
        return when {
            lowered.contains("hant") || lowered.endsWith("-tw") ||
                lowered.endsWith("-hk") || lowered.endsWith("-mo") -> "zh-Hant"

            lowered.contains("hans") || lowered.endsWith("-cn") ||
                lowered.endsWith("-sg") -> "zh-Hans"

            else -> "zh"
        }
    }

    private fun normalizeLanguageSubtag(value: String): String =
        when (value.length) {
            2 -> value.uppercase(Locale.ROOT)
            4 -> value.lowercase(Locale.ROOT).replaceFirstChar { it.uppercaseChar() }
            else -> value.lowercase(Locale.ROOT)
        }

    private fun extractVssId(value: String): String? {
        val trimmed = value.trim()
        if (trimmed.isEmpty() || trimmed.length > 64 || ' ' in trimmed || "://" in trimmed) {
            return null
        }
        return if (languageFromVssId(trimmed) != null) trimmed else null
    }

    private fun languageFromVssId(value: String): String? {
        val trimmed = value.trim()
        if (trimmed.isEmpty() || trimmed == "-") return null

        val candidate = when {
            trimmed.startsWith("a.", ignoreCase = true) ->
                trimmed.substring(2).substringBefore('.')
            trimmed.startsWith(".") ->
                trimmed.substring(1).substringBefore('.')
            trimmed.startsWith("c.", ignoreCase = true) ->
                trimmed.substring(2).substringBefore('.')
            trimmed.startsWith("t.", ignoreCase = true) ->
                trimmed.substringAfterLast(".")
            else -> return null
        }
        return normalizeLanguageCode(candidate)
    }
}
