package icu.nullptr.polyglot.captions.engine

import icu.nullptr.polyglot.captions.CaptionCue
import java.text.Normalizer
import java.util.Locale
import kotlin.math.max
import kotlin.math.min

/**
 * Semantic subtitle chunker adapted from Anchored AI Captions (`RebuildPlanner`) for PolyglotYT's
 * native Xposed cue timeline and `OverlayUpdateHook` incremental streams.
 */
object SubtitleChunker {
    const val FIRST_BLOCK_AIM_MS = 6_000L
    const val NEXT_BLOCK_AIM_MS = 14_000L
    const val MAX_ASR_WORDS = 160
    const val MAX_ASR_CHARS = 1_600
    const val MAX_ASR_SPAN_MS = 30_000L

    const val MAX_AUTHORED_CUES = 4
    const val MAX_AUTHORED_CHARS = 600
    const val MAX_AUTHORED_SPAN_MS = 20_000L

    const val HARD_GAP_MS = 650L
    const val CONTEXT_ASR_TOKENS = 24
    const val CONTEXT_AUTHORED_TOKENS = 600
    const val MAX_CONTEXT_CHARS = 360

    const val ROLLING_MERGE_MAX_GAP_MS = 2_000L
    const val ROLLING_MERGE_MAX_SPAN_MS = 20_000L
    const val DEFAULT_ESTIMATED_CUE_MS = 3_000L
    const val DEFAULT_IMMEDIATE_MAX_CUES = 6

    private val tokenRegex = Regex(
        "[\\p{IsHan}\\p{IsHiragana}\\p{IsKatakana}\\p{IsHangul}]" +
            "|[+-]?\\p{N}+(?:[.,:/-]\\p{N}+)*(?:[a-zA-Z]+)?(?:%|％)?" +
            "|[\\p{L}\\p{M}]+(?:[.'’_\\-][\\p{L}\\p{M}\\p{N}]+)*|[^\\s]",
    )
    private val keyEdgeRegex = Regex("^[^\\p{L}\\p{N}+\\-]+|[^\\p{L}\\p{N}%]+$")
    private val terminalRegex = Regex("(?s).*[.!?。！？؟۔।॥׃።][\\\"'”’）)\\]}》】]*$")
    private val abbreviationRegex =
        Regex("(?i).*(?:\\bMr|\\bMrs|\\bDr|\\bProf|\\bvs|\\betc)\\.[\\\"'”’）)\\]}》】]*$")
    private val comparativeLeadRegex = Regex("(?is).*\\b(more|less|rather)\\b.*")

    private val pivotRegex =
        Regex("^(if|because|although|unless|but|while|however|whereas|instead|secondly|thirdly|finally)\\b.*")
    private val andClauseRegex =
        Regex("^and (then|so|finally|critically|yet|i|we|it|this|that|while)\\b.*")
    private val comeYearRegex = Regex("^come [12][0-9]{3}\\b.*")
    private val pronounVerbRegex = Regex(
        "^(it|this|that|they|we|he|she|i) (is|was|were|are|has|have|had|will|would|can|could|do|did)\\b.*",
    )
    private val articleNounVerbRegex = Regex(
        "^(the|a|an) [a-z]+(?: [a-z]+)? (is|was|were|are|has|have|had|will|would|can|could)\\b.*",
    )
    private val subjectReportingRegex = Regex(
        "^[a-z][a-z'-]+ (reduced|increased|announced|decided|said|argued|explained|aims|plans)\\b.*",
    )
    private val inYearVerbRegex = Regex(
        "^in [12][0-9]{3} (?:[a-z]+ ){1,2}(?:could|can|had|has|was|were|is|are)\\b.*",
    )
    private val theHeadNounRegex = Regex(
        "^the (reality|creation|question|point|goal|reason|problem|result|argument)\\b.*",
    )

    private val comeSet = wordSet("come|comes|coming|came")
    private val contrastSet = wordSet("and|but|however")
    private val ordinalSet = wordSet("firstly|secondly|thirdly|finally|then")
    private val joinerSet = wordSet("and|but|or")
    private val comparativeSet = wordSet("than|then")
    private val dependentSet = wordSet(
        "if|because|although|though|while|which|that|so|as|than|and|or|but|to|of|with|without|" +
            "for|from|in|on|at|by|about|including|into|between|like|rather|whether|unless|until|" +
            "before|after|where|when|what|who|how|more|less|not|no|its|their|his|her|this|that|" +
            "a|an|the|every|each|any|some|another|firstly|secondly|thirdly",
    )
    private val notSubjectSet = wordSet(
        "and|or|but|then|also|was|were|is|are|be|been|being|has|have|had|can|could|will|would|" +
            "not|never|that|which|who",
    )
    private val reportingSet = wordSet(
        "reduced|increased|announced|decided|said|argued|explained|aims|plans",
    )
    private val weakEndSet = wordSet(
        "a|an|the|of|to|with|without|and|or|not|no|very|particularly|more|less|than|as",
    )
    private val cjkDependentSet = wordSet(
        "の|が|を|に|で|と|は|も|へ|や|から|まで|より|って|ば|たら|ながら|ので|のに|けど|けれど|" +
            "しかし|そして|また|でも|だから|ところが|けれども|しかしながら|それで|つまり|すなわち|ただし|なお|一方|一方で|" +
            "的|地|得|了|着|过|過|和|与|與|及|或|而|但|因为|因為|所以|如果|虽然|雖然|" +
            "当|當|在|从|從|向|对|對|把|被|이|가|을|를|은|는|에|에서|와|과|로|으로|의|도|만|까지|부터",
    )
    private val cjkDependentSuffixes: List<String> =
        cjkDependentSet.sortedByDescending { it.length }

    private const val OPENING_PUNCT = "([{（【《“‘\""
    private const val TRAILING_STRIP_PUNCT = "，,、；;：: ”’\"'」』）)]》】"

    fun inferAutoGenerated(
        cues: List<CaptionCue>,
        explicitAutoGenerated: Boolean? = null,
    ): Boolean {
        if (explicitAutoGenerated != null) return explicitAutoGenerated
        if (cues.size < 2) return false

        var overlaps = 0
        var validPairs = 0
        var unpunctuated = 0
        for (i in cues.indices) {
            val cur = cues[i]
            val text = CaptionCue.normalize(cur.text)
            if (!isTerminal(text)) {
                unpunctuated++
            }
            if (i + 1 < cues.size) {
                val next = cues[i + 1]
                if (cur.startMs >= 0L && cur.endMs > cur.startMs && next.startMs >= 0L) {
                    validPairs++
                    if (next.startMs < cur.endMs) {
                        overlaps++
                    }
                }
            }
        }
        if (validPairs > 0 && overlaps * 10 > validPairs) return true
        return cues.size >= 6 && unpunctuated * 10 > cues.size * 7
    }

    /**
     * Collapses adjacent rolling prefix/suffix or duplicate cues emitted by `OverlayUpdateHook`
     * when `gapMs <= 2000ms` and `mergedDurationMs <= 20000ms`.
     */
    fun collapseRollingCues(cues: List<CaptionCue>): List<CaptionCue> {
        if (cues.isEmpty()) return emptyList()
        val result = ArrayList<CaptionCue>(cues.size)

        for (raw in cues) {
            val text = CaptionCue.normalize(raw.text)
            if (text.isEmpty()) continue
            val normalizedCue = raw.copy(text = text)

            val prev = result.lastOrNull()
            if (prev == null) {
                result += normalizedCue
                continue
            }

            val merged = tryMergeRollingPair(prev, normalizedCue)
            if (merged != null) {
                result[result.lastIndex] = merged
            } else {
                result += normalizedCue
            }
        }
        return result
    }

    /**
     * Builds immediate foreground micro-batches for `OverlayUpdateHook` streams (Shorts / Live)
     * when full timeline data is unavailable.
     */
    fun buildImmediateBlocks(
        cues: List<CaptionCue>,
        recentHistory: List<String> = emptyList(),
        startBlockIndex: Int = 0,
        startCueIndex: Int = 0,
        maxCuesPerBlock: Int = DEFAULT_IMMEDIATE_MAX_CUES,
    ): List<PlannedBlock> {
        val collapsed = collapseRollingCues(cues)
        if (collapsed.isEmpty()) return emptyList()

        val cueCap = maxCuesPerBlock.coerceAtLeast(1)
        val indexed = buildIndexedCues(collapsed, startCueIndex)
        val historyTokens = recentHistory.flatMap { tokenize(CaptionCue.normalize(it)) }
        val blocks = ArrayList<PlannedBlock>()

        var from = 0
        while (from < indexed.size) {
            var to = from
            var chars = indexed[from].normalizedText.length
            while (to + 1 < indexed.size) {
                val next = indexed[to + 1]
                val count = to - from + 1
                val span = next.endMs - indexed[from].startMs
                if (count >= cueCap ||
                    chars + next.normalizedText.length > MAX_AUTHORED_CHARS ||
                    span > MAX_AUTHORED_SPAN_MS
                ) {
                    break
                }
                to++
                chars += next.normalizedText.length
            }

            val slice = indexed.subList(from, to + 1).toList()
            val precedingTokens = buildList {
                addAll(historyTokens)
                for (k in 0 until from) {
                    addAll(tokenize(indexed[k].normalizedText))
                }
            }
            val followingTokens = buildList {
                for (k in (to + 1) until indexed.size) {
                    addAll(tokenize(indexed[k].normalizedText))
                }
            }
            val contextBefore = trimContextBefore(
                precedingTokens.takeLast(CONTEXT_ASR_TOKENS),
                MAX_CONTEXT_CHARS,
            )
            val contextAfter = trimContextAfter(
                followingTokens.take(CONTEXT_ASR_TOKENS),
                MAX_CONTEXT_CHARS,
            )
            val blockIdx = startBlockIndex + blocks.size
            val endMs = slice.maxOf { it.endMs }
            blocks += PlannedBlock(
                blockIndex = blockIdx,
                id = "imm${blockIdx}_${slice.first().cueIndex}_${slice.last().cueIndex}",
                cues = slice,
                startMs = slice.first().startMs,
                endMs = endMs,
                isAuthored = false,
                contextBefore = contextBefore,
                contextAfter = contextAfter,
                continuedBefore = false,
                continuedAfter = false,
                isImmediate = true,
            )
            from = to + 1
        }
        return blocks
    }

    /**
     * Plans semantic translation blocks over a full or prefix-growing subtitle timeline.
     */
    fun planTimeline(
        cues: List<CaptionCue>,
        isAutoGenerated: Boolean? = null,
        sourceLanguage: String = "auto",
        maxCuesPerBlock: Int = Int.MAX_VALUE,
    ): List<PlannedBlock> {
        val indexed = buildIndexedCues(cues, startCueIndex = 0)
        if (indexed.isEmpty()) return emptyList()

        val autoTrack = inferAutoGenerated(cues, isAutoGenerated)
        val authored = !autoTrack
        val cueLimit = maxCuesPerBlock.coerceAtLeast(1)
        val analyzed = buildAnalyzedTrack(indexed, sourceLanguage)

        val rawRanges: List<IntRange> = if (authored) {
            planAuthoredRanges(analyzed, min(MAX_AUTHORED_CUES, cueLimit))
        } else {
            planAsrRanges(analyzed, cueLimit)
        }

        val contextWindowTokens = if (authored) CONTEXT_AUTHORED_TOKENS else CONTEXT_ASR_TOKENS
        return rawRanges.mapIndexed { blockIndex, range ->
            val firstCue = range.first
            val lastCue = range.last
            val slice = indexed.subList(firstCue, lastCue + 1).toList()

            val firstTokenIdx = analyzed.cueTokenStart[firstCue]
            val lastTokenIdx = analyzed.cueTokenEnd[lastCue]

            val beforeFrom = max(0, firstTokenIdx - contextWindowTokens)
            val beforeTokens = if (firstTokenIdx > 0) {
                analyzed.allTokens.subList(beforeFrom, firstTokenIdx)
            } else {
                emptyList()
            }

            val afterTo = min(analyzed.allTokens.size, lastTokenIdx + 1 + contextWindowTokens)
            val afterTokens = if (lastTokenIdx + 1 < analyzed.allTokens.size) {
                analyzed.allTokens.subList(lastTokenIdx + 1, afterTo)
            } else {
                emptyList()
            }

            val continuedBefore = firstCue > 0 && !isBoundary(analyzed, firstCue - 1)
            val continuedAfter = lastCue + 1 < indexed.size && !isBoundary(analyzed, lastCue)

            PlannedBlock(
                blockIndex = blockIndex,
                id = "b${blockIndex}_${slice.first().cueIndex}_${slice.last().cueIndex}",
                cues = slice,
                startMs = slice.first().startMs,
                endMs = slice.maxOf { it.endMs },
                isAuthored = authored,
                contextBefore = trimContextBefore(beforeTokens, MAX_CONTEXT_CHARS),
                contextAfter = trimContextAfter(afterTokens, MAX_CONTEXT_CHARS),
                continuedBefore = continuedBefore,
                continuedAfter = continuedAfter,
                isImmediate = false,
            )
        }
    }

    internal fun isTerminal(text: String): Boolean {
        if (text.isEmpty()) return false
        var hasCandidate = false
        for (ch in text) {
            if (".!?。！？؟۔।॥׃።".indexOf(ch) >= 0) {
                hasCandidate = true
                break
            }
        }
        return hasCandidate && terminalRegex.matches(text) && !abbreviationRegex.matches(text)
    }

    internal fun tokenize(text: String): List<String> {
        if (text.isEmpty()) return emptyList()
        val result = ArrayList<String>()
        for (match in tokenRegex.findAll(text)) {
            val token = match.value
            val lexical = token.codePoints().anyMatch { Character.isLetterOrDigit(it) }
            if (!lexical && result.isNotEmpty() && OPENING_PUNCT.indexOf(token) < 0) {
                result[result.lastIndex] = result.last() + token
            } else {
                result += token
            }
        }
        return result
    }

    private fun planAuthoredRanges(track: AnalyzedTrack, maxCues: Int): List<IntRange> {
        val out = ArrayList<IntRange>()
        var from = 0
        val cues = track.cues
        while (from < cues.size) {
            var to = from
            var cueCount = 1
            var chars = cues[from].normalizedText.length
            while (to + 1 < cues.size) {
                val next = cues[to + 1]
                val nextStartSpan = next.startMs - cues[from].startMs
                val nextFullSpan = next.endMs - cues[from].startMs
                if (cueCount >= maxCues ||
                    chars + next.normalizedText.length > MAX_AUTHORED_CHARS ||
                    nextStartSpan > MAX_AUTHORED_SPAN_MS ||
                    nextFullSpan > MAX_ASR_SPAN_MS ||
                    isBoundary(track, to) ||
                    isHardBreakBefore(track, to + 1)
                ) {
                    break
                }
                to++
                cueCount++
                chars += next.normalizedText.length
            }
            out += from..to
            from = to + 1
        }
        return out
    }

    private fun planAsrRanges(track: AnalyzedTrack, maxCues: Int): List<IntRange> {
        val out = ArrayList<IntRange>()
        val cues = track.cues
        var from = 0
        while (from < cues.size) {
            var end = from
            var lastBoundary = -1
            var words = 0
            var chars = 0
            val aimMs = if (out.isEmpty()) FIRST_BLOCK_AIM_MS else NEXT_BLOCK_AIM_MS

            for (i in from until cues.size) {
                val cue = cues[i]
                val cueWords = track.cueTokenCount(i)
                val cueChars = cue.normalizedText.length
                val span = cue.endMs - cues[from].startMs

                if (i > from && (
                        (i - from) >= maxCues ||
                            words + cueWords > MAX_ASR_WORDS ||
                            chars + cueChars > MAX_ASR_CHARS ||
                            span > MAX_ASR_SPAN_MS
                        )
                ) {
                    break
                }

                end = i
                words += cueWords
                chars += cueChars

                if (out.isEmpty() &&
                    span >= FIRST_BLOCK_AIM_MS &&
                    i + 1 < cues.size &&
                    isSafeCut(track, i) &&
                    resourceScore(track, i) >= 50
                ) {
                    break
                }

                if (isBoundary(track, i)) {
                    lastBoundary = i
                    if (span >= aimMs || i + 1 == cues.size || isHardBreakBefore(track, i + 1)) {
                        break
                    }
                }
            }

            if (lastBoundary >= from) {
                end = lastBoundary
            } else if (end + 1 < cues.size && end > from) {
                var best = end
                var bestScore = Int.MIN_VALUE
                val lowerBound = from + (end - from) / 2
                for (i in end downTo (lowerBound + 1)) {
                    if (!isSafeCut(track, i)) continue
                    val candidateScore = resourceScore(track, i)
                    if (candidateScore > bestScore) {
                        best = i
                        bestScore = candidateScore
                    }
                }
                if (bestScore != Int.MIN_VALUE) {
                    end = best
                } else if (isDependentEnding(track, end)) {
                    for (i in (end - 1) downTo from) {
                        if (isSafeCut(track, i)) {
                            end = i
                            break
                        }
                    }
                }
            }

            out += from..end
            from = end + 1
        }
        return out
    }

    private fun isHardBreakBefore(track: AnalyzedTrack, cueIdx: Int): Boolean {
        if (cueIdx <= 0 || cueIdx >= track.cues.size) return false
        val prev = track.cues[cueIdx - 1]
        val cur = track.cues[cueIdx]
        return (cur.startMs - prev.endMs >= HARD_GAP_MS) || cur.normalizedText.startsWith(">>")
    }

    private fun isBoundary(track: AnalyzedTrack, cueIdx: Int): Boolean {
        val cues = track.cues
        if (cueIdx < 0 || cueIdx >= cues.size) return false
        return isTerminal(cues[cueIdx].normalizedText) ||
            cueIdx + 1 == cues.size ||
            isHardBreakBefore(track, cueIdx + 1)
    }

    private fun isSafeCut(track: AnalyzedTrack, cueIdx: Int): Boolean =
        cueIdx in track.cues.indices &&
            !isDependentEnding(track, cueIdx) &&
            !isProtectedCut(track, cueIdx)

    private fun isDependentEnding(track: AnalyzedTrack, cueIdx: Int): Boolean {
        if (cueIdx !in track.cues.indices) return false
        val cueText = track.cues[cueIdx].normalizedText
        if (isTerminal(cueText)) return false

        val lastTokenIdx = track.cueTokenEnd[cueIdx]
        val lastKey = track.allKeys[lastTokenIdx]
        if (track.englishSource) {
            val prevKey = if (lastTokenIdx > 0) track.allKeys[lastTokenIdx - 1] else ""
            val nextKey = if (lastTokenIdx + 1 < track.allKeys.size) track.allKeys[lastTokenIdx + 1] else ""
            if (lastKey == "from" && prevKey in comeSet && nextKey in contrastSet) {
                return false
            }
            if (lastKey in ordinalSet && prevKey in joinerSet) {
                return true
            }
            return lastKey in dependentSet
        }

        if (lastKey in cjkDependentSet) return true
        val stripped = cueText.trimEnd { TRAILING_STRIP_PUNCT.indexOf(it) >= 0 }
        if (stripped.isEmpty()) return false
        return cjkDependentSuffixes.any { suffix -> suffix.length > 1 && stripped.endsWith(suffix) }
    }

    private fun isProtectedCut(track: AnalyzedTrack, cueIdx: Int): Boolean {
        if (!track.englishSource || cueIdx < 0 || cueIdx + 1 >= track.cues.size || isBoundary(track, cueIdx)) {
            return false
        }
        val leftIdx = track.cueTokenEnd[cueIdx]
        val rightIdx = track.cueTokenStart[cueIdx + 1]
        val leftKey = track.allKeys[leftIdx]
        val rightKey = track.allKeys[rightIdx]

        if (leftKey in comparativeSet) {
            val windowFrom = max(0, leftIdx - 35)
            val windowText = joinTokens(track.allTokens.subList(windowFrom, leftIdx + 1))
            if (comparativeLeadRegex.matches(windowText)) {
                return true
            }
        }
        return rightKey in reportingSet && isLowerLexicalWord(leftKey) && leftKey !in notSubjectSet
    }

    private fun resourceScore(track: AnalyzedTrack, cueIdx: Int): Int {
        if (cueIdx < 0 || cueIdx + 1 >= track.cues.size) return 60
        val cueText = track.cues[cueIdx].normalizedText
        val lastKey = track.allKeys[track.cueTokenEnd[cueIdx]]

        if (!track.englishSource) {
            if (isBoundary(track, cueIdx)) return 60
            if (isDependentEnding(track, cueIdx)) return -100
            if (endsWithClauseCommaOrSemicolon(cueText)) return 30
            return 25
        }

        if (isDependentEnding(track, cueIdx) ||
            isProtectedCut(track, cueIdx) ||
            lastKey in weakEndSet ||
            isNumericToken(lastKey)
        ) {
            return -100
        }

        val nextStart = track.cueTokenStart[cueIdx + 1]
        val nextEnd = min(track.allTokens.size, nextStart + 8)
        val nextText = joinTokens(track.allTokens.subList(nextStart, nextEnd)).lowercase(Locale.ROOT)

        if (pivotRegex.matches(nextText) ||
            (nextText.startsWith("and ") && andClauseRegex.matches(nextText)) ||
            (nextText.startsWith("come ") && comeYearRegex.matches(nextText))
        ) {
            return 60
        }

        if (pronounVerbRegex.matches(nextText) ||
            articleNounVerbRegex.matches(nextText) ||
            subjectReportingRegex.matches(nextText) ||
            (nextText.startsWith("in ") && inYearVerbRegex.matches(nextText)) ||
            (nextText.startsWith("the ") && theHeadNounRegex.matches(nextText)) ||
            nextText.startsWith("i'm ") ||
            nextText.startsWith("let's ")
        ) {
            return 50
        }

        if (endsWithClauseCommaOrSemicolon(cueText)) {
            return 30
        }
        return 25
    }

    private fun endsWithClauseCommaOrSemicolon(text: String): Boolean {
        val trimmed = text.trim()
        if (trimmed.isEmpty()) return false
        val last = trimmed.last()
        return last == ',' || last == '，' || last == ';' || last == '；' || last == '、'
    }

    private fun trimContextBefore(tokens: List<String>, maxChars: Int): String {
        if (tokens.isEmpty()) return ""
        var lo = 0
        val hi = tokens.lastIndex
        var joined = joinTokens(tokens.subList(lo, hi + 1))
        while (joined.length > maxChars && lo < hi) {
            lo++
            joined = joinTokens(tokens.subList(lo, hi + 1))
        }
        return if (joined.length <= maxChars) joined else joined.takeLast(maxChars).trimStart()
    }

    private fun trimContextAfter(tokens: List<String>, maxChars: Int): String {
        if (tokens.isEmpty()) return ""
        val lo = 0
        var hi = tokens.lastIndex
        var joined = joinTokens(tokens.subList(lo, hi + 1))
        while (joined.length > maxChars && hi > lo) {
            hi--
            joined = joinTokens(tokens.subList(lo, hi + 1))
        }
        return if (joined.length <= maxChars) joined else joined.take(maxChars).trimEnd()
    }

    private fun joinTokens(tokens: List<String>): String {
        if (tokens.isEmpty()) return ""
        val sb = StringBuilder()
        for (token in tokens) {
            if (token.isEmpty()) continue
            if (sb.isNotEmpty() && needsSpace(sb, token)) {
                sb.append(' ')
            }
            sb.append(token)
        }
        return sb.toString()
    }

    private fun needsSpace(prior: StringBuilder, next: String): Boolean {
        val left = prior.codePointBefore(prior.length)
        val right = next.codePointAt(0)
        if (isCjk(left) || isCjk(right) || isCompactPunctuation(left)) return false
        if (!Character.isLetterOrDigit(right)) return false
        return "([{（【《“‘".indexOf(String(Character.toChars(left))) < 0
    }

    private fun isCjk(cp: Int): Boolean =
        when (Character.UnicodeScript.of(cp)) {
            Character.UnicodeScript.HAN,
            Character.UnicodeScript.HIRAGANA,
            Character.UnicodeScript.KATAKANA,
            Character.UnicodeScript.HANGUL,
            -> true
            else -> false
        }

    private fun isCompactPunctuation(cp: Int): Boolean =
        cp in 0x3000..0x303F ||
            cp in 0xFF00..0xFFEF ||
            cp == 0x2018 ||
            cp == 0x2019 ||
            cp == 0x201C ||
            cp == 0x201D ||
            cp == 0x2026 ||
            cp == 0x2014

    private fun buildIndexedCues(cues: List<CaptionCue>, startCueIndex: Int): List<IndexedCue> {
        val rawFiltered = ArrayList<CaptionCue>(cues.size)
        for (cue in cues) {
            val normalized = CaptionCue.normalize(cue.text)
            if (normalized.isEmpty()) continue
            val prev = rawFiltered.lastOrNull()
            if (prev != null &&
                prev.text == normalized &&
                prev.startMs == cue.startMs &&
                prev.endMs == cue.endMs
            ) {
                continue
            }
            rawFiltered += cue.copy(text = normalized)
        }
        if (rawFiltered.isEmpty()) return emptyList()

        val result = ArrayList<IndexedCue>(rawFiltered.size)
        var monotonicStart = 0L
        for (i in rawFiltered.indices) {
            val cur = rawFiltered[i]
            val startMs = if (cur.startMs >= 0L) {
                max(monotonicStart, cur.startMs)
            } else {
                monotonicStart
            }
            val nextKnownStart = rawFiltered.getOrNull(i + 1)?.startMs?.takeIf { it > startMs }
            val endMs = when {
                cur.endMs > startMs -> cur.endMs
                nextKnownStart != null -> min(nextKnownStart, startMs + DEFAULT_ESTIMATED_CUE_MS)
                else -> startMs + DEFAULT_ESTIMATED_CUE_MS
            }
            monotonicStart = startMs
            result += IndexedCue(
                cueIndex = startCueIndex + i,
                startMs = startMs,
                endMs = endMs,
                normalizedText = cur.text,
                windowId = cur.windowId,
            )
        }
        return result
    }

    private fun tryMergeRollingPair(prev: CaptionCue, next: CaptionCue): CaptionCue? {
        val prevText = prev.text
        val nextText = next.text
        if (prevText.isEmpty() || nextText.isEmpty()) return null

        val bothStartsKnown = prev.startMs >= 0L && next.startMs >= 0L
        if (bothStartsKnown) {
            val prevEffectiveEnd = if (prev.endMs >= prev.startMs) prev.endMs else prev.startMs
            val gapMs = next.startMs - prevEffectiveEnd
            if (gapMs > ROLLING_MERGE_MAX_GAP_MS || next.startMs < prev.startMs - 500L) {
                return null
            }
            val mergedEndCandidate = max(
                if (prev.endMs >= 0L) prev.endMs else prev.startMs,
                if (next.endMs >= 0L) next.endMs else next.startMs,
            )
            if (mergedEndCandidate - prev.startMs > ROLLING_MERGE_MAX_SPAN_MS) {
                return null
            }
        }

        val mergedStart = when {
            prev.startMs >= 0L -> prev.startMs
            else -> next.startMs
        }
        val mergedEnd = when {
            prev.endMs >= 0L && next.endMs >= 0L -> max(prev.endMs, next.endMs)
            next.endMs >= 0L -> next.endMs
            else -> prev.endMs
        }

        if (prevText.equals(nextText, ignoreCase = true)) {
            return prev.copy(startMs = mergedStart, endMs = mergedEnd)
        }
        if (isRollingPrefixOf(shorter = prevText, longer = nextText)) {
            return next.copy(startMs = mergedStart, endMs = mergedEnd, text = nextText)
        }
        if (isRollingSuffixOf(longer = prevText, shorter = nextText)) {
            return prev.copy(startMs = mergedStart, endMs = mergedEnd, text = prevText)
        }
        return null
    }

    private fun isRollingPrefixOf(shorter: String, longer: String): Boolean {
        if (shorter.length >= longer.length || !longer.startsWith(shorter)) return false
        val boundaryAfter = longer[shorter.length]
        return boundaryAfter.isWhitespace() ||
            isCjk(boundaryAfter.code) ||
            isCjk(shorter.last().code)
    }

    private fun isRollingSuffixOf(longer: String, shorter: String): Boolean {
        if (shorter.length >= longer.length || !longer.endsWith(shorter)) return false
        val idxBefore = longer.length - shorter.length - 1
        val boundaryBefore = longer[idxBefore]
        return boundaryBefore.isWhitespace() ||
            isCjk(boundaryBefore.code) ||
            isCjk(shorter.first().code)
    }

    private fun buildAnalyzedTrack(
        cues: List<IndexedCue>,
        sourceLanguage: String,
    ): AnalyzedTrack {
        val allTokens = ArrayList<String>(cues.size * 6)
        val allKeys = ArrayList<String>(cues.size * 6)
        val starts = IntArray(cues.size)
        val ends = IntArray(cues.size)

        for (i in cues.indices) {
            starts[i] = allTokens.size
            val tokens = tokenize(cues[i].normalizedText).ifEmpty { listOf(cues[i].normalizedText) }
            for (token in tokens) {
                allTokens += token
                allKeys += tokenKey(token)
            }
            ends[i] = allTokens.lastIndex
        }

        val normalizedLang = sourceLanguage.trim().lowercase(Locale.ROOT)
        val englishSource = when {
            normalizedLang == "en" || normalizedLang.startsWith("en-") || normalizedLang.startsWith("en_") -> true
            normalizedLang.isNotEmpty() && normalizedLang != "auto" -> false
            else -> inferEnglishFromTokens(allTokens)
        }

        return AnalyzedTrack(
            cues = cues,
            allTokens = allTokens,
            allKeys = allKeys,
            cueTokenStart = starts,
            cueTokenEnd = ends,
            englishSource = englishSource,
        )
    }

    private fun inferEnglishFromTokens(tokens: List<String>): Boolean {
        var asciiLetters = 0
        var totalLetters = 0
        val sampleLimit = min(tokens.size, 80)
        for (i in 0 until sampleLimit) {
            for (ch in tokens[i]) {
                if (ch.isLetter()) {
                    totalLetters++
                    if (ch in 'a'..'z' || ch in 'A'..'Z') asciiLetters++
                }
            }
        }
        return totalLetters > 0 && asciiLetters * 10 >= totalLetters * 8
    }

    private fun tokenKey(token: String): String {
        val folded = Normalizer.normalize(token, Normalizer.Form.NFKC)
            .lowercase(Locale.ROOT)
            .replace('’', '\'')
            .replace('−', '-')
        return keyEdgeRegex.replace(folded, "")
    }

    private fun isLowerLexicalWord(value: String): Boolean {
        if (value.length < 2 || value[0] !in 'a'..'z') return false
        for (i in 1 until value.length) {
            val ch = value[i]
            if (ch !in 'a'..'z' && ch != '\'' && ch != '-') return false
        }
        return true
    }

    private fun isNumericToken(value: String): Boolean {
        val start = if (value.isNotEmpty() && (value[0] == '+' || value[0] == '-')) 1 else 0
        return start < value.length && value[start] in '0'..'9'
    }

    private fun wordSet(pipeSeparated: String): Set<String> =
        pipeSeparated.split('|').filter { it.isNotEmpty() }.toHashSet()

    private class AnalyzedTrack(
        val cues: List<IndexedCue>,
        val allTokens: List<String>,
        val allKeys: List<String>,
        val cueTokenStart: IntArray,
        val cueTokenEnd: IntArray,
        val englishSource: Boolean,
    ) {
        fun cueTokenCount(cueIdx: Int): Int =
            (cueTokenEnd[cueIdx] - cueTokenStart[cueIdx] + 1).coerceAtLeast(1)
    }
}
