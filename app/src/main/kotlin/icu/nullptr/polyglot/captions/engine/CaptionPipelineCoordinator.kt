package icu.nullptr.polyglot.captions.engine

import icu.nullptr.polyglot.captions.CaptionCue
import icu.nullptr.polyglot.captions.CaptionLanguageState
import icu.nullptr.polyglot.captions.CaptionSession
import icu.nullptr.polyglot.translate.TranslationManager
import java.io.Closeable
import java.util.concurrent.ConcurrentHashMap

/**
 * Pure JVM-testable coordinator bridging native subtitle hooks ([CaptionSession], [CaptionLanguageState])
 * with [SubtitleChunker], [DualQueueScheduler], and [TranslationManager] L1/L2 caching.
 *
 * Guarantees zero disk or network blocking on the caller (UI/hook) thread.
 */
class CaptionPipelineCoordinator(
    val session: CaptionSession = CaptionSession(),
    private val runtimeConfigProvider: () -> TranslationManager.RuntimeConfig = TranslationManager::currentRuntimeConfig,
    private val sourceLanguageProvider: () -> String = CaptionLanguageState::currentSourceLanguage,
    private val autoGeneratedProvider: () -> Boolean? = { CaptionLanguageState.currentTrack()?.isAutoGenerated },
    private val clockMs: () -> Long = { System.nanoTime() / 1_000_000L },
    private val logger: ((String, Throwable?) -> Unit)? = null,
    private val onRefreshUi: (updatedOriginals: Set<String>, expectedSessionEpoch: Long, source: String) -> Unit = { _, _, _ -> },
    schedulerFactory: ((BlockTranslator, BlockCacheLookup, TranslationPublishListener) -> DualQueueScheduler)? = null,
) : Closeable {

    private data class EpochBinding(
        val uiEpoch: Long,
        val sourceLanguage: String,
        val config: TranslationManager.RuntimeConfig,
    )

    private val coordLock = Any()
    private val epochBindings = ConcurrentHashMap<Long, EpochBinding>()

    @Volatile
    private var activeSchedulerEpoch: Long = 0L

    @Volatile
    private var activeUiEpoch: Long = session.currentEpoch()

    @Volatile
    private var wasEnabled: Boolean = true

    @Volatile
    private var lastRenderedAnchorStartMs: Long = CaptionCue.UNKNOWN_TIME_MS

    private var lastTimelineLoadedAtMs: Long = UNSET_TIME_MS
    private var hasUnpairedTrack: Boolean = false
    private var awaitingTrackMetadataForTimeline: Boolean = false
    private var lastPlannedSourceLanguage: String = "auto"
    private var lastPlannedAutoGenerated: Boolean? = null
    private var timelineTextSet: Set<String> = emptySet()

    private val publishListener = object : TranslationPublishListener {
        override fun onProvisional(
            sessionEpoch: Long,
            generation: Int,
            cue: IndexedCue,
            translated: String,
        ) {
            if (sessionEpoch != scheduler.currentSessionEpoch()) return
            val uiEpoch = epochBindings[sessionEpoch]?.uiEpoch ?: session.currentEpoch()
            if (session.putProvisionalTranslation(cue.normalizedText, translated, uiEpoch)) {
                onRefreshUi(setOf(cue.normalizedText), uiEpoch, "provisional")
            }
        }

        override fun onBlockPublished(
            sessionEpoch: Long,
            generation: Int,
            block: PlannedBlock,
            plan: BlockTranslationPlan,
        ) {
            if (sessionEpoch != scheduler.currentSessionEpoch()) return
            if (plan.translationsByText.isEmpty()) return
            val uiEpoch = epochBindings[sessionEpoch]?.uiEpoch ?: session.currentEpoch()

            val written = session.putFinalTranslations(plan.translationsByText, uiEpoch)
            if (written > 0) {
                onRefreshUi(plan.translationsByText.keys, uiEpoch, "block_${block.id}")
            }
        }

        override fun onCacheableEntries(
            sessionEpoch: Long,
            entries: Map<IndexedCue, String>,
        ) {
            if (entries.isEmpty()) return
            val binding = epochBindings[sessionEpoch] ?: currentFallbackBinding()
            TranslationManager.cacheTranslations(
                entries = entries,
                sourceLanguage = binding.sourceLanguage,
                config = binding.config,
            )
        }
    }

    private val blockTranslator = BlockTranslator { block, cuesToTranslate, isPriority, control ->
        val schedEpoch = scheduler.currentSessionEpoch()
        val binding = epochBindings[schedEpoch] ?: currentFallbackBinding()
        TranslationManager.translateBlock(
            block = block,
            cuesToTranslate = cuesToTranslate,
            sourceLanguage = binding.sourceLanguage,
            isPriority = isPriority,
            engineControl = control,
            config = binding.config,
        )
    }

    private val blockCacheLookup = BlockCacheLookup { block ->
        val schedEpoch = scheduler.currentSessionEpoch()
        val binding = epochBindings[schedEpoch] ?: currentFallbackBinding()
        TranslationManager.lookupBlockCache(
            block = block,
            sourceLanguage = binding.sourceLanguage,
            config = binding.config,
        )
    }

    val scheduler: DualQueueScheduler = schedulerFactory?.invoke(
        blockTranslator,
        blockCacheLookup,
        publishListener,
    ) ?: DualQueueScheduler(
        translator = blockTranslator,
        cacheLookup = blockCacheLookup,
        listener = publishListener,
        clockMs = clockMs,
        logger = logger,
    )

    init {
        bindEpochLocked(
            schedEpoch = scheduler.currentSessionEpoch(),
            uiEpoch = session.currentEpoch(),
            sourceLanguage = sourceLanguageProvider(),
            config = runtimeConfigProvider(),
        )
    }

    /**
     * Synchronizes module enable switch and translation config signature.
     * Retires background work immediately when disabled, and re-schedules from current playback
     * position when provider/targetLanguage/endpoint/model changes.
     */
    fun syncRuntimeState(): Boolean {
        val cfg = runtimeConfigProvider()
        if (!cfg.enabled) {
            var disabledEpoch: Long? = null
            if (wasEnabled) {
                synchronized(coordLock) {
                    if (wasEnabled) {
                        wasEnabled = false
                        val retiredEpoch = scheduler.retireCurrentSession("module_disabled")
                        activeSchedulerEpoch = retiredEpoch
                        disabledEpoch = session.currentEpoch()
                    }
                }
            }
            disabledEpoch?.let { epoch ->
                onRefreshUi(emptySet(), epoch, "module_disabled")
            }
            return false
        }

        val currentUiEpoch = session.currentEpoch()
        if (!wasEnabled || currentUiEpoch != activeUiEpoch) {
            var refreshEpoch: Long? = null
            synchronized(coordLock) {
                val refreshedUiEpoch = session.currentEpoch()
                if (!wasEnabled || refreshedUiEpoch != activeUiEpoch) {
                    wasEnabled = true
                    val srcLang = sourceLanguageProvider()
                    val isAsr = autoGeneratedProvider()
                    val resumePosMs = scheduler.playbackTracker.estimatePositionMs(clockMs())
                    val newSchedEpoch = scheduler.onNewSession("config_or_state_changed")
                    bindEpochLocked(newSchedEpoch, refreshedUiEpoch, srcLang, cfg)

                    val existingTimeline = session.currentTimelineCues()
                    if (existingTimeline.isNotEmpty()) {
                        prefillFromMemoryCache(existingTimeline, srcLang, cfg, refreshedUiEpoch)
                        scheduler.submitTimeline(
                            cues = existingTimeline,
                            isAutoGenerated = isAsr,
                            sourceLanguage = srcLang,
                            maxCuesPerBlock = TranslationManager.maxCuesPerBlock(cfg.provider),
                        )
                        bindEpochLocked(scheduler.currentSessionEpoch(), refreshedUiEpoch, srcLang, cfg)
                        if (resumePosMs > 0L) {
                            scheduler.onPlaybackPosition(startMs = resumePosMs)
                        }
                    }
                    refreshEpoch = refreshedUiEpoch
                }
            }
            refreshEpoch?.let { epoch ->
                onRefreshUi(emptySet(), epoch, "config_changed")
            }
        }
        return true
    }

    fun onConfigChanged(key: String) {
        val enabledNow = syncRuntimeState()
        if (enabledNow && key == "bilingual_order") {
            onRefreshUi(emptySet(), session.currentEpoch(), "subtitle_mode_changed")
        }
    }

    fun onTimelineBuilt(rawCues: List<CaptionCue>): List<PlannedBlock> {
        if (!syncRuntimeState()) return emptyList()
        if (rawCues.isEmpty()) return emptyList()

        var refreshedL1Keys: Set<String> = emptySet()
        var publishUiEpoch = session.currentEpoch()
        val planned: List<PlannedBlock>

        synchronized(coordLock) {
            val hadExistingTimeline = session.currentTimelineCues().isNotEmpty()
            val obs = session.observeTimelineCues(rawCues)
            if (obs.allCues.isEmpty()) return emptyList()

            val cfg = runtimeConfigProvider()
            val srcLang = sourceLanguageProvider()
            val isAsr = autoGeneratedProvider()
            publishUiEpoch = obs.epoch

            val isFreshTimelineTrack = obs.replacedTrack || !hadExistingTimeline
            if (obs.replacedTrack) {
                lastRenderedAnchorStartMs = CaptionCue.UNKNOWN_TIME_MS
                val newSchedEpoch = scheduler.onNewSession("timeline_track_replaced")
                bindEpochLocked(newSchedEpoch, obs.epoch, srcLang, cfg)
            } else {
                bindEpochLocked(scheduler.currentSessionEpoch(), obs.epoch, srcLang, cfg)
            }

            if (isFreshTimelineTrack) {
                if (hasUnpairedTrack) {
                    // Track arrived first and is now paired with this timeline.
                    hasUnpairedTrack = false
                    awaitingTrackMetadataForTimeline = false
                } else {
                    // Timeline arrived before its CaptionTrack hook -> allow single coalesced metadata update.
                    awaitingTrackMetadataForTimeline = true
                }
            }

            refreshedL1Keys = prefillFromMemoryCache(obs.allCues, srcLang, cfg, obs.epoch)
            timelineTextSet = obs.allCues.asSequence().map { it.normalizedText() }.toHashSet()
            lastTimelineLoadedAtMs = clockMs()
            lastPlannedSourceLanguage = srcLang
            lastPlannedAutoGenerated = isAsr

            planned = scheduler.submitTimeline(
                cues = obs.allCues,
                isAutoGenerated = isAsr,
                sourceLanguage = srcLang,
                maxCuesPerBlock = TranslationManager.maxCuesPerBlock(cfg.provider),
            )
            bindEpochLocked(scheduler.currentSessionEpoch(), obs.epoch, srcLang, cfg)
        }

        if (refreshedL1Keys.isNotEmpty()) {
            onRefreshUi(refreshedL1Keys, publishUiEpoch, "timeline_l1_hit")
        }
        return planned
    }

    fun onOverlayCues(rawCues: List<CaptionCue>) {
        if (!syncRuntimeState()) return
        val collapsed = SubtitleChunker.collapseRollingCues(rawCues)
        if (collapsed.isEmpty()) return

        val anchorCue = collapsed.lastOrNull { it.startMs >= 0L }
            ?: collapsed.firstOrNull { it.startMs >= 0L }
        if (anchorCue != null) {
            session.updateAnchorByTime(anchorCue.startMs)
            scheduler.onPlaybackPosition(
                startMs = anchorCue.startMs,
                endMs = anchorCue.endMs,
            )
        }

        val cfg = runtimeConfigProvider()
        val srcLang = sourceLanguageProvider()
        val uiEpoch = session.currentEpoch()
        val l1Hits = prefillFromMemoryCache(collapsed, srcLang, cfg, uiEpoch)
        if (l1Hits.isNotEmpty()) {
            onRefreshUi(l1Hits, uiEpoch, "overlay_l1_hit")
        }

        val unseen = session.observeNewCues(collapsed)
        if (unseen.isEmpty()) return

        val knownTimeline = timelineTextSet
        val immediateCandidates = unseen.filter { cue ->
            val norm = cue.normalizedText()
            norm.isNotEmpty() &&
                norm !in knownTimeline &&
                session.translationFor(norm) == null
        }
        if (immediateCandidates.isEmpty()) return

        synchronized(coordLock) {
            bindEpochLocked(scheduler.currentSessionEpoch(), session.currentEpoch(), srcLang, cfg)
            scheduler.submitImmediateCues(
                cues = immediateCandidates,
                maxCuesPerBlock = TranslationManager.immediateMaxCuesPerBlock(cfg.provider),
            )
        }
    }

    fun resolveForRender(rawText: CharSequence?): CaptionSession.CaptionTranslation? {
        if (rawText == null) return null
        if (!syncRuntimeState()) return null

        val raw = rawText.toString()
        val normalized = CaptionCue.normalize(raw)
        if (normalized.isEmpty()) return null

        maybeAdvancePlaybackFromRenderedText(normalized)

        session.resolveTranslation(raw)?.let { return it }

        // Fast zero-IO L1 check in case another session/video populated shared memory LRU.
        val cfg = runtimeConfigProvider()
        val srcLang = sourceLanguageProvider()
        val uiEpoch = session.currentEpoch()
        if ('\n' in raw || '\r' in raw) {
            val lines = CaptionCue.normalizeLines(raw)
            if (lines.size >= 2) {
                var anyStored = false
                for (line in lines) {
                    val hit = TranslationManager.lookupMemoryOnly(line, srcLang, cfg)
                    if (hit != null && session.putFinalTranslation(line, hit, uiEpoch)) {
                        anyStored = true
                    }
                }
                if (anyStored) {
                    session.resolveTranslation(raw)?.let { return it }
                }
            }
        } else {
            val hit = TranslationManager.lookupMemoryOnly(normalized, srcLang, cfg)
            if (hit != null && session.putFinalTranslation(normalized, hit, uiEpoch)) {
                return CaptionSession.CaptionTranslation(normalized, hit)
            }
        }

        return null
    }

    /**
     * Handles a YouTube `CaptionTrack` update. Returns `true` when renderer states should be wiped,
     * or `false` if the track either did not change or arrived right after its own timeline load.
     */
    fun onCaptionTrackObserved(track: Any?, source: String): Boolean {
        if (!CaptionLanguageState.updateFromCaptionTrack(track, source)) {
            return false
        }

        synchronized(coordLock) {
            val now = clockMs()
            val cfg = runtimeConfigProvider()
            val newSrcLang = sourceLanguageProvider()
            val newAsr = autoGeneratedProvider()
            val existingTimeline = session.currentTimelineCues()

            if (awaitingTrackMetadataForTimeline &&
                existingTimeline.isNotEmpty() &&
                lastTimelineLoadedAtMs != UNSET_TIME_MS &&
                now - lastTimelineLoadedAtMs in 0L..TIMELINE_TRACK_COALESCE_WINDOW_MS
            ) {
                // Consume one-shot pairing immediately so any subsequent track switch resets cleanly.
                awaitingTrackMetadataForTimeline = false
                hasUnpairedTrack = false
                if (newSrcLang != lastPlannedSourceLanguage || newAsr != lastPlannedAutoGenerated) {
                    val uiEpoch = session.invalidateTranslations()
                    val schedEpoch = scheduler.onNewSession("track_metadata_refined")
                    bindEpochLocked(schedEpoch, uiEpoch, newSrcLang, cfg)
                    lastPlannedSourceLanguage = newSrcLang
                    lastPlannedAutoGenerated = newAsr
                    prefillFromMemoryCache(existingTimeline, newSrcLang, cfg, uiEpoch)
                    if (cfg.enabled) {
                        scheduler.submitTimeline(
                            cues = existingTimeline,
                            isAutoGenerated = newAsr,
                            sourceLanguage = newSrcLang,
                            maxCuesPerBlock = TranslationManager.maxCuesPerBlock(cfg.provider),
                        )
                        bindEpochLocked(scheduler.currentSessionEpoch(), uiEpoch, newSrcLang, cfg)
                    }
                }
                return false
            }

            session.clear()
            timelineTextSet = emptySet()
            lastRenderedAnchorStartMs = CaptionCue.UNKNOWN_TIME_MS
            lastTimelineLoadedAtMs = UNSET_TIME_MS
            hasUnpairedTrack = true
            awaitingTrackMetadataForTimeline = false
            lastPlannedSourceLanguage = newSrcLang
            lastPlannedAutoGenerated = newAsr
            val newSchedEpoch = scheduler.onNewSession("caption_track_changed")
            bindEpochLocked(newSchedEpoch, session.currentEpoch(), newSrcLang, cfg)
            return true
        }
    }

    fun onTranslationCacheCleared() {
        var refreshEpoch: Long
        synchronized(coordLock) {
            val cfg = runtimeConfigProvider()
            val srcLang = sourceLanguageProvider()
            val isAsr = autoGeneratedProvider()
            val resumePosMs = scheduler.playbackTracker.estimatePositionMs(clockMs())
            val uiEpoch = session.invalidateTranslations()
            refreshEpoch = uiEpoch
            val newSchedEpoch = scheduler.onNewSession("translation_cache_cleared")
            bindEpochLocked(newSchedEpoch, uiEpoch, srcLang, cfg)

            val timeline = session.currentTimelineCues()
            if (cfg.enabled && timeline.isNotEmpty()) {
                scheduler.submitTimeline(
                    cues = timeline,
                    isAutoGenerated = isAsr,
                    sourceLanguage = srcLang,
                    maxCuesPerBlock = TranslationManager.maxCuesPerBlock(cfg.provider),
                )
                bindEpochLocked(scheduler.currentSessionEpoch(), uiEpoch, srcLang, cfg)
                if (resumePosMs > 0L) {
                    scheduler.onPlaybackPosition(startMs = resumePosMs)
                }
            }
        }
        onRefreshUi(emptySet(), refreshEpoch, "cache_cleared")
    }

    override fun close() {
        scheduler.close()
        epochBindings.clear()
    }

    private fun maybeAdvancePlaybackFromRenderedText(normalized: String) {
        if (normalized !in timelineTextSet) return
        val cue = session.findNearestObservedCue(normalized) ?: return
        if (cue.startMs < 0L || cue.startMs == lastRenderedAnchorStartMs) return
        lastRenderedAnchorStartMs = cue.startMs
        session.updateAnchorByTime(cue.startMs)
        scheduler.onPlaybackPosition(startMs = cue.startMs, endMs = cue.endMs)
    }

    private fun prefillFromMemoryCache(
        cues: Iterable<CaptionCue>,
        sourceLanguage: String,
        config: TranslationManager.RuntimeConfig,
        expectedUiEpoch: Long,
    ): Set<String> {
        val hits = TranslationManager.lookupMemoryOnlyBatch(cues, sourceLanguage, config)
        if (hits.isEmpty()) return emptySet()
        session.putFinalTranslations(hits, expectedUiEpoch)
        return hits.keys
    }

    private fun bindEpochLocked(
        schedEpoch: Long,
        uiEpoch: Long,
        sourceLanguage: String,
        config: TranslationManager.RuntimeConfig,
    ) {
        activeSchedulerEpoch = schedEpoch
        activeUiEpoch = uiEpoch
        epochBindings[schedEpoch] = EpochBinding(
            uiEpoch = uiEpoch,
            sourceLanguage = sourceLanguage,
            config = config,
        )
        if (epochBindings.size > MAX_RETAINED_EPOCH_BINDINGS) {
            val minKeep = schedEpoch - MAX_RETAINED_EPOCH_BINDINGS / 2
            val iter = epochBindings.keys.iterator()
            while (iter.hasNext()) {
                if (iter.next() < minKeep) {
                    iter.remove()
                }
            }
        }
    }

    private fun currentFallbackBinding(): EpochBinding =
        EpochBinding(
            uiEpoch = activeUiEpoch,
            sourceLanguage = sourceLanguageProvider(),
            config = runtimeConfigProvider(),
        )

    companion object {
        const val TIMELINE_TRACK_COALESCE_WINDOW_MS = 600L
        private const val UNSET_TIME_MS = Long.MIN_VALUE / 2
        private const val MAX_RETAINED_EPOCH_BINDINGS = 32
    }
}
